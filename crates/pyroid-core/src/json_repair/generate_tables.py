"""Generate `tables.rs`: Python's `str` predicates per Unicode version.

json_repair's parser branches on `str.isspace()`, `str.isalpha()`,
`str.isdigit()` and `str.isalnum()`, whose answers depend on the Unicode
database of the running interpreter. Every table is dumped from CPython itself
by testing every code point, then written as sorted inclusive ranges; tables
that are identical in several versions are emitted once and shared.

Usage (Linux or a Linux container; `/target/venv-$v` stands for a venv per CPython version):

    # 1. dump one JSON file per interpreter (one per Unicode version)
    for v in 3.11 3.12 3.13 3.14 3.15; do
        uv run --no-project -p $v python -I generate_tables.py dump /tmp/gen/$v.json
    done
    # 2. check the dumps and write tables.rs
    python generate_tables.py emit /tmp/gen/*.json
    # 3. optional: a per-code-point oracle for the full-range test in chars.rs
    python generate_tables.py oracle /tmp/gen/oracle-3.13.txt
    PYROID_JSONREPAIR_CHARS_ORACLE=/tmp/gen/oracle-3.13.txt \\
        cargo test -p pyroid-core --lib json_repair::chars
"""

from __future__ import annotations

import json
import sys
import unicodedata
from itertools import pairwise
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = (
    "// @generated by generate_tables.py -- do not edit by hand.\n"
    "// Derived from json_repair 0.64.9 (MIT), © Stefano Baccianella; modified.\n"
)
MAX_CP = 0x110000
VERSIONS = ["14.0.0", "15.0.0", "15.1.0", "16.0.0", "17.0.0"]
PREDICATES = {
    "space": str.isspace,
    "alpha": str.isalpha,
    "digit": str.isdigit,
    "alnum": str.isalnum,
}
# Bits of one oracle digit (see `oracle`); chars.rs decodes the same layout.
ORACLE_BITS = {"space": 1, "alpha": 2, "digit": 4, "alnum": 8}
# Code points the Rust side can never hold as themselves: real surrogates, and
# U+10F800..U+10FFFF, which stand for remapped lone surrogates.
FORBIDDEN = [(0xD800, 0xDFFF), (0x10F800, 0x10FFFF)]


# --------------------------------------------------------------------------
# dump / oracle: run under one interpreter
# --------------------------------------------------------------------------


def _ranges(pred) -> list[list[int]]:
    """Inclusive code point ranges where `pred(chr(cp))` holds."""
    out: list[list[int]] = []
    start = None
    for cp in range(MAX_CP + 1):
        hit = cp < MAX_CP and pred(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append([start, cp - 1])
            start = None
    return out


def dump(path: str) -> None:
    data = {
        "python": sys.version.split()[0],
        "unicode": unicodedata.unidata_version,
        "props": {name: _ranges(pred) for name, pred in PREDICATES.items()},
    }
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(json.dumps(data))
    print(f"wrote {path}: Python {data['python']}, Unicode {data['unicode']}")


def oracle(path: str) -> None:
    """One hex digit per code point (bits as in ORACLE_BITS), after a header line."""
    digits = []
    for cp in range(MAX_CP):
        ch = chr(cp)
        bits = 0
        for name, pred in PREDICATES.items():
            if pred(ch):
                bits |= ORACLE_BITS[name]
        digits.append("0123456789abcdef"[bits])
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(unicodedata.unidata_version + "\n" + "".join(digits) + "\n")
    print(f"wrote {path}: Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}")


# --------------------------------------------------------------------------
# emit: combine the dumps and write Rust
# --------------------------------------------------------------------------


def _ascii(ranges: list[list[int]]) -> set[int]:
    return {cp for a, b in ranges for cp in range(a, b + 1) if cp < 0x80}


def _check(d: dict) -> None:
    """The invariants chars.rs relies on."""
    p = d["props"]
    for name, ranges in p.items():
        for (_, b), (a, _) in pairwise(ranges):
            assert b + 1 < a, (d["python"], name, b, a)  # sorted, disjoint, maximal
        for a, b in ranges:
            assert a <= b, (d["python"], name, a, b)
            for lo, hi in FORBIDDEN:
                assert b < lo or a > hi, (d["python"], name, a, b)
    # The ASCII fast paths in chars.rs.
    letters = {*range(ord("A"), ord("Z") + 1), *range(ord("a"), ord("z") + 1)}
    digits = set(range(ord("0"), ord("9") + 1))
    assert _ascii(p["alpha"]) == letters, d["python"]
    assert _ascii(p["digit"]) == digits, d["python"]
    assert _ascii(p["alnum"]) == letters | digits, d["python"]
    assert _ascii(p["space"]) == {*range(0x09, 0x0E), *range(0x1C, 0x21)}, d["python"]


def _emit_ranges(name: str, ranges: list[list[int]], attr: str = "") -> str:
    body = ", ".join(f"(0x{a:x}, 0x{b:x})" for a, b in ranges)
    return f"{attr}pub(super) static {name}: [(u32, u32); {len(ranges)}] = [{body}];\n"


def emit(paths: list[str]) -> None:
    dumps = [json.loads(Path(p).read_text()) for p in paths]
    dumps.sort(key=lambda d: [int(x) for x in d["unicode"].split(".")])
    assert [d["unicode"] for d in dumps] == VERSIONS, [d["unicode"] for d in dumps]
    for d in dumps:
        _check(d)
    space = dumps[0]["props"]["space"]
    for d in dumps[1:]:
        assert d["props"]["space"] == space, f"isspace differs on Python {d['python']}"

    out = [
        HEADER,
        "//! Python's `str.isspace` / `isalpha` / `isdigit` / `isalnum` per Unicode\n",
        "//! version: sorted, disjoint, inclusive code point ranges dumped from CPython.\n",
        "//! Tables that are identical in several versions are shared.\n\n",
        "#![allow(clippy::unreadable_literal)]\n\n",
        "/// The tables of one Unicode version.\n",
        "#[derive(Debug)]\n",
        "pub(super) struct VersionTables {\n",
        "    pub(super) alpha: &'static [(u32, u32)],\n",
        "    pub(super) digit: &'static [(u32, u32)],\n",
        "    pub(super) alnum: &'static [(u32, u32)],\n",
        "}\n\n",
        "/// `str.isspace` (identical in every supported version; chars.rs spells it out).\n",
        _emit_ranges("SPACE", space, "#[cfg(test)]\n"),
    ]
    names: dict[tuple[str, str], str] = {}  # (kind, table) -> static name
    per_version: list[tuple[dict, dict[str, str]]] = []
    for d in dumps:
        tag = "_".join(d["unicode"].split(".")[:2])
        chosen = {}
        for kind in ("alpha", "digit", "alnum"):
            key = (kind, json.dumps(d["props"][kind]))
            if key not in names:
                names[key] = f"{kind.upper()}_{tag}"
                out.append(f"\n/// `str.is{kind}` from Unicode {d['unicode']} on.\n")
                out.append(_emit_ranges(names[key], d["props"][kind]))
            chosen[kind] = names[key]
        per_version.append((d, chosen))
    for d, chosen in per_version:
        tag = "_".join(d["unicode"].split(".")[:2])
        out.append(f"\n/// Unicode {d['unicode']} (CPython {d['python']}).\n")
        out.append(f"pub(super) static V{tag}: VersionTables = VersionTables {{\n")
        out.extend(f"    {kind}: &{chosen[kind]},\n" for kind in ("alpha", "digit", "alnum"))
        out.append("};\n")
    (HERE / "tables.rs").write_text("".join(out))
    print("wrote tables.rs:", ", ".join(sorted(names.values())))
    print("versions:", ", ".join(f"{d['unicode']}={d['python']}" for d in dumps))


if __name__ == "__main__":
    if len(sys.argv) >= 3 and sys.argv[1] == "dump":
        dump(sys.argv[2])
    elif len(sys.argv) >= 3 and sys.argv[1] == "oracle":
        oracle(sys.argv[2])
    elif len(sys.argv) >= 3 and sys.argv[1] == "emit":
        emit(sys.argv[2:])
    else:
        raise SystemExit(__doc__)
