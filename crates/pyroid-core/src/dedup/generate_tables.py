# Derived from datatrove 0.10.1 (Apache-2.0), © HuggingFace Inc.; modified.
"""Generate `simplify_tables.rs`, the character data behind `pyroid_core::dedup::simplify`.

Nothing is transcribed by hand: every property is read back from the running interpreters.

* Per CPython version (Unicode 14.0, 15.0, 15.1, 16.0, 17.0): `str.lower()` per code point,
  the Final_Sigma classes (probed through `str.lower()` itself), general category Mn, which
  code points `unicodedata.normalize("NFD", ...)` treats as non-inert, and `str.isspace()`.
* `\\p{Decimal_Number}` as the `regex` module sees it (its own Unicode data, any interpreter).
* datatrove's `PUNCTUATION` string, from the installed datatrove 0.10.1.

Usage (Linux or a Linux container; `/target/venv-$v` stands for a venv per CPython version):

    # 1. one dump per interpreter (each needs `regex`; one of them needs datatrove)
    for v in 311 312 parity 314 315; do
        /target/venv-$v/bin/python generate_tables.py dump /target/gen-simplify/$v.json
    done
    # 2. merge them (checks the version-independent parts agree) and write the Rust file
    #    (formatted with rustfmt, which must be on PATH)
    python3 generate_tables.py emit /target/gen-simplify/*.json

Encoding. Every code point gets a class id from a two-level table (64-entry blocks, deduplicated).
A class is one flags byte per Unicode version, so a property that changes for an already-assigned
character is just another class; `emit` lists every such change (none so far) in the file header.
Lowercase mappings are delta ranges (stride 1 or 2) from the newest version, plus explicit entries
for multi-character mappings and for any version whose mapping differs from the newest.
"""

# ruff: noqa: PT018, RUF001  (a build script, not a test; look-alike characters on purpose)

from __future__ import annotations

import itertools
import json
import re
import subprocess
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT_RS = HERE / "simplify_tables.rs"
HEADER = (
    "// @generated by generate_tables.py -- do not edit by hand.\n"
    "// Derived from datatrove 0.10.1 (Apache-2.0), © HuggingFace Inc.; modified.\n"
)
MAX_CP = 0x110000
VERSIONS = ["14.0.0", "15.0.0", "15.1.0", "16.0.0", "17.0.0"]
SIGMA, SMALL_SIGMA, FINAL_SIGMA = "Σ", "σ", "ς"
# `NUMBERS_PATTERN`'s separator class.
SEPARATORS = ".,،٫⎖⎗⎘"
# What `crate::text::is_py_whitespace` implements.
PY_WHITESPACE = [*range(0x09, 0x0E), *range(0x1C, 0x21), 0x85, 0xA0, 0x1680, *range(0x2000, 0x200B)]
PY_WHITESPACE += [0x2028, 0x2029, 0x202F, 0x205F, 0x3000]

# Per-version flag bits, then the version-independent ones.
LOWER, CI, CASED, MN, NFDX = 1, 2, 4, 8, 16
DIGIT, PUNCT, WS = 32, 64, 128
PER_VERSION = {"lower": LOWER, "ci": CI, "cased": CASED, "mn": MN, "nfdx": NFDX}
# The plane-14 tags and variation selectors live in their own small window.
TAGS_START, TAGS_END = 0xE0000, 0xE1000


def _code_points():
    return (cp for cp in range(MAX_CP) if not 0xD800 <= cp <= 0xDFFF)


def _ranges(cps) -> list[list[int]]:
    out: list[list[int]] = []
    for cp in sorted(cps):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def _expand(ranges) -> set[int]:
    return {cp for a, b in ranges for cp in range(a, b + 1)}


# --------------------------------------------------------------------------
# dump: run under one interpreter
# --------------------------------------------------------------------------


def dump(out: str) -> None:
    import regex

    digit_re, space_re = regex.compile(r"\p{Decimal_Number}"), re.compile(r"\s")
    sets: dict[str, set[int]] = {
        k: set() for k in ("lower", "ci", "cased", "mn", "nfdx", "space", "digit")
    }
    lower: dict[int, str] = {}
    non_mn_ccc: list[list[int]] = []
    for cp in _code_points():
        c = chr(cp)
        cat = unicodedata.category(c)
        low = c.lower()
        if low != c:
            sets["lower"].add(cp)
            if c != SIGMA:
                lower[cp] = low
        # handle_capital_sigma (Objects/unicodeobject.c): a capital sigma becomes final when the
        # nearest non-case-ignorable character before it is cased and the nearest one after it
        # is not. Only "case-ignorable" and "cased, not case-ignorable" matter to it.
        after_cased = (c + SIGMA).lower()[-1] == FINAL_SIGMA
        after_cased_or_ignorable = ("A" + c + SIGMA).lower()[-1] == FINAL_SIGMA
        before_cased = ("A" + SIGMA + c).lower()[1] == SMALL_SIGMA
        assert before_cased == after_cased, hex(cp)
        assert after_cased_or_ignorable or not after_cased, hex(cp)
        if after_cased:
            sets["cased"].add(cp)
        elif after_cased_or_ignorable:
            sets["ci"].add(cp)
        if cat == "Mn":
            sets["mn"].add(cp)
        ccc = unicodedata.combining(c)
        if cat != "Cn" and (ccc or unicodedata.normalize("NFD", c) != c):
            sets["nfdx"].add(cp)
        if ccc and cat != "Mn":
            non_mn_ccc.append([cp, ccc])
        sp = c.isspace()
        assert sp == (space_re.match(c) is not None) == (not c.strip()), hex(cp)
        if sp:
            sets["space"].add(cp)
        if digit_re.match(c):
            sets["digit"].add(cp)
    sep_re = regex.compile(r"[.,،٫⎖⎗⎘]", regex.VERBOSE | regex.UNICODE)
    assert {cp for cp in _code_points() if sep_re.match(chr(cp))} == {ord(s) for s in SEPARATORS}
    try:
        from datatrove.utils.text import PUNCTUATION
    except ImportError:
        PUNCTUATION = None  # noqa: N806
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text(
        json.dumps(
            {
                "unicode": unicodedata.unidata_version,
                "python": sys.version.split()[0],
                "regex": regex.__version__,
                "sets": {k: _ranges(v) for k, v in sets.items()},
                "lower": {str(k): v for k, v in sorted(lower.items())},
                "non_mn_ccc": non_mn_ccc,
                "punctuation": PUNCTUATION,
            }
        )
    )
    sys.stderr.write(
        f"{out}: Unicode {unicodedata.unidata_version}, Python {sys.version.split()[0]}\n"
    )


# --------------------------------------------------------------------------
# emit: merge the dumps into Rust
# --------------------------------------------------------------------------


def _rows(items: list[str], per_line: int) -> str:
    lines = [", ".join(items[i : i + per_line]) for i in range(0, len(items), per_line)]
    return "\n    " + ",\n    ".join(lines) + ",\n" if items else ""


def _rust_str(s: str) -> str:
    def esc(c: str) -> str:
        return c if " " <= c < "\x7f" and c not in '"\\' else f"\\u{{{ord(c):x}}}"

    return '"' + "".join(map(esc, s)) + '"'


def _lower_ranges(mapping: dict[int, int]) -> list[tuple[int, int, int, int]]:
    """Single-character mappings as (start, end, delta, stride) runs, stride 1 or 2."""
    runs: list[list[int]] = []  # start, end, delta, stride
    for cp in sorted(mapping):
        d = mapping[cp] - cp
        if runs:
            s, e, rd, st = runs[-1]
            if rd == d and (cp - e == st or (s == e and cp - e in (1, 2))):
                runs[-1][1], runs[-1][3] = cp, cp - e
                continue
        runs.append([cp, cp, d, 1])
    return [tuple(r) for r in runs]


def emit(paths: list[str]) -> None:
    dumps = sorted(
        (json.loads(Path(p).read_text()) for p in paths), key=lambda d: VERSIONS.index(d["unicode"])
    )
    assert [d["unicode"] for d in dumps] == VERSIONS, [d["unicode"] for d in dumps]
    nv = len(dumps)

    # ---- version-independent data ----------------------------------------
    for d in dumps:
        assert d["regex"] == dumps[0]["regex"], "use the same regex release everywhere"
        assert d["sets"]["digit"] == dumps[0]["sets"]["digit"], (
            "regex's \\p{Decimal_Number} differs between interpreters"
        )
        assert _expand(d["sets"]["space"]) == set(PY_WHITESPACE), (
            f"str.isspace() changed in {d['unicode']}"
        )
    digits = _expand(dumps[0]["sets"]["digit"])
    puncts = [d["punctuation"] for d in dumps if d["punctuation"] is not None]
    assert puncts and all(p == puncts[0] for p in puncts), (
        "need datatrove in at least one interpreter"
    )
    punct = {ord(c) for c in puncts[0]}
    assert len(punct) == len(puncts[0]), "PUNCTUATION repeats a character"
    # The passes are independent, but sanity-check what the Rust side relies on.
    for s in SEPARATORS:
        assert ord(s) not in digits

    # ---- per-version flags -----------------------------------------------
    flags = [bytearray(MAX_CP) for _ in dumps]
    for i, d in enumerate(dumps):
        for name, bit in PER_VERSION.items():
            for a, b in d["sets"][name]:
                for cp in range(a, b + 1):
                    flags[i][cp] |= bit
    common = bytearray(MAX_CP)
    for cp in digits:
        common[cp] |= DIGIT
    for cp in punct:
        common[cp] |= PUNCT
    for cp in PY_WHITESPACE:
        common[cp] |= WS

    # Stability: once a code point has any property in some version, it should have the same
    # properties in every later version. Anything else is recorded (the class table encodes
    # it regardless).
    changes: list[str] = []
    for cp in _code_points():
        seq = [flags[i][cp] for i in range(nv)]
        nz = [i for i in range(nv) if seq[i]]
        if nz and any(seq[i] != seq[-1] for i in range(nz[0], nv)):
            changes.append(
                f"U+{cp:04X} " + " ".join(f"{dumps[i]['unicode']}:{seq[i]:#04x}" for i in range(nv))
            )

    # ---- class table -----------------------------------------------------
    classes: dict[tuple[int, ...], int] = {(0,) * nv: 0}
    cls = bytearray(MAX_CP)
    for cp in _code_points():
        key = tuple(flags[i][cp] | common[cp] for i in range(nv))
        cls[cp] = classes.setdefault(key, len(classes))
    assert len(classes) <= 256, len(classes)
    nonzero = [cp for cp in range(MAX_CP) if cls[cp]]
    low_max = max(cp for cp in nonzero if cp < TAGS_START)
    assert all(cp < TAGS_END for cp in nonzero), "class data beyond plane-14 tags"
    best = None
    for shift in range(4, 9):
        bs = 1 << shift
        limit = (low_max + bs) & ~(bs - 1)
        blocks: dict[bytes, int] = {}
        windows = [range(0, limit, bs), range(TAGS_START, TAGS_END, bs)]
        stage1 = [
            [blocks.setdefault(bytes(cls[s : s + bs]), len(blocks)) for s in w] for w in windows
        ]
        width = 1 if len(blocks) <= 256 else 2
        size = width * sum(map(len, stage1)) + bs * len(blocks)
        if best is None or size < best[0]:
            best = (size, shift, limit, stage1, blocks, width)
    size, shift, limit, (stage1, stage1_tags), blocks, width = best
    stage2 = b"".join(blocks)
    s1t = "u8" if width == 1 else "u16"

    # ---- lowercase -------------------------------------------------------
    newest = {int(k): v for k, v in dumps[-1]["lower"].items()}
    single = {cp: ord(v) for cp, v in newest.items() if len(v) == 1}
    special: dict[tuple[int, str], int] = {}  # (cp, mapping) -> version mask
    for cp, v in newest.items():
        if len(v) != 1:
            special[(cp, v)] = 0
    for i, d in enumerate(dumps):
        for k, v in d["lower"].items():
            cp = int(k)
            if newest.get(cp) != v or len(v) != 1:
                special[(cp, v)] = special.get((cp, v), 0) | 1 << i
    # Single-character entries the newest version does not have (or maps differently) for some
    # older version are covered by `special`; make sure nothing else is needed.
    for d in dumps:
        for k, v in d["lower"].items():
            cp = int(k)
            assert (cp, v) in special or single.get(cp) == ord(v), hex(cp)
    lower_runs = _lower_ranges(single)
    for cp, m in single.items():
        hits = [r for r in lower_runs if r[0] <= cp <= r[1] and (cp - r[0]) % r[3] == 0]
        assert len(hits) == 1 and cp + hits[0][2] == m
    for a, b in itertools.pairwise(lower_runs):
        assert a[1] < b[0]
    lower_versions_differ = [
        f"U+{cp:04X} -> {v!r} in mask {m:#x}" for (cp, v), m in special.items() if len(v) == 1
    ]

    # ---- non-Mn characters with a non-zero combining class (test data) ---
    non_mn = {tuple(x) for d in dumps for x in d["non_mn_ccc"]}
    assert len({cp for cp, _ in non_mn}) == len(non_mn), "combining class changed"

    # ---- write -----------------------------------------------------------
    o = [HEADER]
    o.append("//! Character data for `simplify_text`, per CPython version ")
    o.append("(see `generate_tables.py`).\n")
    o.append("//!\n//! Sources: ")
    o.append(", ".join(f"CPython {d['python']} (Unicode {d['unicode']})" for d in dumps))
    o.append(
        f"; regex {dumps[0]['regex']} for `\\p{{Decimal_Number}}`;"
        " datatrove 0.10.1 `PUNCTUATION`.\n"
    )
    o.append("//!\n//! Properties that changed for an already-assigned code point:")
    o.append("".join(f"\n//! - {c}" for c in changes) if changes else " none.")
    o.append("\n//!\n//! Lowercase mappings that differ between versions:")
    differ = "".join(f"\n//! - {c}" for c in lower_versions_differ)
    o.append(differ or " none.")
    o.append("\n\n#![allow(clippy::unreadable_literal)]\n\n")
    o.append("/// Per-version flag bits (`CLASSES[class][version]`).\n")
    for name, bit in [("LOWER", LOWER), ("CI", CI), ("CASED", CASED), ("MN", MN), ("NFDX", NFDX)]:
        o.append(f"pub(super) const {name}: u8 = {bit};\n")
    o.append("/// Version-independent flag bits, repeated in every version's byte.\n")
    for name, bit in [("DIGIT", DIGIT), ("PUNCT", PUNCT), ("WS", WS)]:
        o.append(f"pub(super) const {name}: u8 = {bit};\n")
    o.append(f"\npub(super) const SHIFT: u32 = {shift};\n")
    o.append("/// Code points from here up to `TAGS_START` are all class 0.\n")
    o.append(f"pub(super) const LIMIT: u32 = {limit:#x};\n")
    o.append(f"pub(super) const TAGS_START: u32 = {TAGS_START:#x};\n")
    o.append(f"pub(super) const TAGS_END: u32 = {TAGS_END:#x};\n")
    o.append("\n/// Class flags per Unicode version (14.0, 15.0, 15.1, 16.0, 17.0).\n")
    o.append(f"pub(super) static CLASSES: [[u8; {nv}]; {len(classes)}] = [")
    o.append(_rows(["[" + ", ".join(f"{b:#04x}" for b in k) + "]" for k in classes], 4))
    o.append("];\n\n/// Block index of `cp >> SHIFT`, for `cp < LIMIT`.\n")
    o.append(f"pub(super) static STAGE1: [{s1t}; {len(stage1)}] = [")
    o.append(_rows([str(x) for x in stage1], 32) + "];\n")
    o.append("\n/// Block index of `(cp - TAGS_START) >> SHIFT`.\n")
    o.append(f"pub(super) static STAGE1_TAGS: [{s1t}; {len(stage1_tags)}] = [")
    o.append(_rows([str(x) for x in stage1_tags], 32) + "];\n")
    o.append("\n/// Class ids, `1 << SHIFT` per block.\n")
    o.append(f"pub(super) static STAGE2: [u8; {len(stage2)}] = [")
    o.append(_rows([str(x) for x in stage2], 32) + "];\n")
    o.append("\n/// Single-character lowercase mappings (newest version) as\n")
    o.append("/// `(first, last, delta, stride)`: `cp` maps to `cp + delta` if\n")
    o.append("/// `first <= cp <= last` and `(cp - first) % stride == 0`.\n")
    o.append(f"pub(super) static LOWER_RUNS: [(u32, u32, i32, u32); {len(lower_runs)}] = [")
    o.append(_rows([f"({a:#x}, {b:#x}, {d}, {s})" for a, b, d, s in lower_runs], 4) + "];\n")
    o.append("\n/// Lowercase mappings `LOWER_RUNS` does not give: multi-character ones, and\n")
    o.append("/// any that differ between versions, as `(cp, version mask, mapping)`, sorted\n")
    o.append("/// by `cp`.\n")
    sp = sorted(special.items())
    o.append(f"pub(super) static LOWER_SPECIAL: [(u32, u8, &str); {len(sp)}] = [")
    o.append(_rows([f"({cp:#x}, {m:#04x}, {_rust_str(v)})" for (cp, v), m in sp], 2) + "];\n")
    o.append("\n/// datatrove's `PUNCTUATION`, ASCII part (bit = code point).\n")
    o.append(f"pub(super) const PUNCT_ASCII: u128 = {sum(1 << c for c in punct if c < 128):#x};\n")
    nm = sorted(non_mn)
    o.append("\n/// Non-Mn characters with a non-zero combining class (the only ones whose\n")
    o.append("/// class shows in the output), `(cp, ccc)`.\n#[cfg(test)]\n")
    o.append(f"pub(super) static NON_MN_CCC: [(u32, u8); {len(nm)}] = [")
    o.append(_rows([f"({cp:#x}, {c})" for cp, c in nm], 8) + "];\n")
    o.append("\n/// `str.isspace()` (identical in every supported version).\n#[cfg(test)]\n")
    o.append(f"pub(super) static PY_WHITESPACE: [u32; {len(PY_WHITESPACE)}] = [")
    o.append(_rows([f"{c:#x}" for c in PY_WHITESPACE], 12) + "];\n")
    OUT_RS.write_text("".join(o))
    # `cargo fmt --check` covers this file too.
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT_RS)], check=True)
    sys.stderr.write(
        f"wrote {OUT_RS.name}: {len(classes)} classes, shift {shift}, {len(blocks)} blocks, "
        f"stage1 {len(stage1)}+{len(stage1_tags)} x {s1t}, {size} table bytes; "
        f"{len(lower_runs)} lower runs, {len(sp)} special; {len(changes)} property changes; "
        f"{len(nm)} non-Mn ccc chars\n"
    )
    for c in changes:
        sys.stderr.write(f"  changed: {c}\n")


if __name__ == "__main__":
    if len(sys.argv) >= 3 and sys.argv[1] == "dump":
        dump(sys.argv[2])
    elif len(sys.argv) >= 3 and sys.argv[1] == "emit":
        emit(sys.argv[2:])
    else:
        raise SystemExit(__doc__)
