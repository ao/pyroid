"""Generate tables.rs from anyascii 0.3.3's table.tsv (ISC licence).

anyascii's own table lists every code point it has a mapping for, including
1,192 that it maps to the empty string on purpose (combining marks, joiners,
tatweel, silent vowel carriers, ...). Code points it does not list have no
mapping. The `any_ascii` crate's packed data returns "" for both, so this
table keeps the difference: it is what `has_transliteration` (and with it
`unidecode`'s ``errors=`` handling) is built on.

Only anyascii data is used. Nothing here reads, or is derived from, Unidecode.

Run from the repository root (Python 3.11+, network access):

    python crates/pyroid-core/src/translit/generate_tables.py [path/to/table.tsv]

Without a path the table is downloaded from the 0.3.3 tag. Its sha256 is
checked either way. If the ``anyascii`` package 0.3.3 is importable, every
code point is also checked against it: listed ones map to their table value,
unlisted ones to "".
"""

import hashlib
import sys
import urllib.request
from pathlib import Path

URL = (
    "https://raw.githubusercontent.com/anyascii/anyascii/"
    "2c07da46be94346fecdc8f5a2c42fa7cf09fca00/table.tsv"
)
SHA256 = "63d405125a149ed646b6f932be96414e2db4b9ff5c3cb1fac49f6386a6fb1fa9"
OUT = Path(__file__).with_name("tables.rs")


def load(path: str | None) -> bytes:
    if path is None:
        with urllib.request.urlopen(URL, timeout=60) as resp:
            data: bytes = resp.read()
    else:
        data = Path(path).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit(f"table.tsv sha256 {digest} != pinned {SHA256}")
    return data


def parse(data: bytes) -> dict[int, str]:
    table: dict[int, str] = {}
    last = 0x7F
    for n, line in enumerate(data.decode("utf-8").split("\n"), 1):
        if not line:
            continue
        key, sep, value = line.partition("\t")
        if not sep or len(key) != 1 or "\t" in value or not value.isascii():
            sys.exit(f"table.tsv line {n}: unexpected format {line!r}")
        cp = ord(key)
        if cp <= last:
            sys.exit(f"table.tsv line {n}: U+{cp:04X} is ASCII or out of order")
        table[cp] = value
        last = cp
    return table


def check_against_package(table: dict[int, str]) -> None:
    try:
        import anyascii  # type: ignore[import-not-found]  # noqa: PLC0415
    except ImportError:
        print("anyascii not installed: skipped the package cross-check")
        return
    if anyascii.__version__ != "0.3.3":
        sys.exit(f"cross-check needs anyascii 0.3.3, found {anyascii.__version__}")
    bad = [
        cp
        for cp in range(0x80, 0x110000)
        if not 0xD800 <= cp <= 0xDFFF and anyascii.anyascii(chr(cp)) != table.get(cp, "")
    ]
    if bad:
        sys.exit(f"{len(bad)} code points differ from the anyascii package, e.g. U+{bad[0]:04X}")
    print("cross-check: every code point matches the anyascii 0.3.3 package")


def ranges(cps: list[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in cps:
        if out and out[-1][1] + 1 == cp:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def main() -> None:
    table = parse(load(sys.argv[1] if len(sys.argv) > 1 else None))
    check_against_package(table)
    empty = ranges([cp for cp, value in table.items() if value == ""])
    n_empty = sum(hi - lo + 1 for lo, hi in empty)
    lines = [
        "// @generated by generate_tables.py from anyascii 0.3.3 table.tsv",
        f"// (sha256 {SHA256}).",
        "// anyascii: Copyright (c) 2020-2025, Hunter WB, ISC License (LICENSES/ISC-anyascii.txt).",
        "// Do not edit by hand.",
        "",
        f"/// The {n_empty} code points anyascii 0.3.3 maps to \"\" on purpose (its table",
        "/// lists them with an empty value), as sorted inclusive ranges. Every other",
        f"/// code point that maps to \"\" is one of the {0x110000 - 0x800 - 0x80 - len(table)}"
        " it has no mapping for.",
        f"/// The table lists {len(table)} non-ASCII code points in all.",
        "pub(super) static EMPTY: &[(u32, u32)] = &[",
        *(f"    (0x{lo:04X}, 0x{hi:04X})," for lo, hi in empty),
        "];",
        "",
        "/// Non-ASCII code points anyascii 0.3.3's table lists (checked by the tests).",
        f"#[cfg(test)]\npub(super) const LISTED_COUNT: usize = {len(table):_};",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}: {len(table)} listed, {n_empty} empty in {len(empty)} ranges")


if __name__ == "__main__":
    main()
