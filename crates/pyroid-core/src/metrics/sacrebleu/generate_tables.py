# Derived from sacrebleu 2.6.0 (Apache-2.0), © Amazon.com, Inc. or its affiliates; modified.
"""Generate ``tables.rs``: the code point classes sacrebleu's ``intl`` and ``zh`` tokenizers use.

Run in the dev container, with sacrebleu 2.6.0 (and the ``regex`` release it installed) in the
venv, from the repository root::

    python crates/pyroid-core/src/metrics/sacrebleu/generate_tables.py
    rustfmt --edition 2024 crates/pyroid-core/src/metrics/sacrebleu/tables.rs

- ``intl`` (``TokenizerV14International``) matches ``\\p{P}``, ``\\p{S}`` and ``\\P{N}`` with the
  third-party ``regex`` module. Each class is read from ``regex`` itself, code point by code
  point, so the table is whatever that ``regex`` release (and its Unicode version) says, not
  what this interpreter's ``unicodedata`` says.
- ``zh`` (``TokenizerZh``) uses ``TokenizerZh._is_chinese_char``, which compares one-character
  strings against ``_UCODE_RANGES``. Some of those bounds are written with five hex digits
  (``'\\u20000'`` is ``'\\u2000' + '0'``), so the real ranges differ from the comments; calling
  the function on every code point captures that exactly.
"""

from __future__ import annotations

import importlib.metadata
import re
import sys
from pathlib import Path

import regex
from sacrebleu.tokenizers.tokenizer_zh import TokenizerZh

OUT = Path(__file__).with_name("tables.rs")
MAX_CP = 0x110000
SURROGATES = range(0xD800, 0xE000)

# Class codes; keep in step with `IntlClass` in tokenizers.rs.
OTHER, PUNCT, SYMBOL, NUMBER = 0, 1, 2, 3


def regex_unicode_version() -> str:
    """The Unicode version the installed ``regex`` release documents in its metadata."""
    meta = importlib.metadata.metadata("regex").get_payload()  # type: ignore[attr-defined]
    found = re.search(r"supports Unicode (\d+\.\d+\.\d+)", str(meta))
    if not found:
        sys.exit("could not find the Unicode version in regex's metadata")
    return found.group(1)


def ranges(classes: list[int]) -> list[tuple[int, int, int]]:
    """Maximal runs ``(first, last, class)`` of code points with the same non-OTHER class."""
    out: list[tuple[int, int, int]] = []
    for cp, cls in enumerate(classes):
        if cls == OTHER:
            continue
        if out and out[-1][1] == cp - 1 and out[-1][2] == cls:
            out[-1] = (out[-1][0], cp, cls)
        else:
            out.append((cp, cp, cls))
    return out


def main() -> None:
    """Write tables.rs."""
    sacrebleu_version = importlib.metadata.version("sacrebleu")
    if sacrebleu_version != "2.6.0":
        sys.exit(f"expected sacrebleu 2.6.0, found {sacrebleu_version}")
    regex_version = importlib.metadata.version("regex")
    unicode_version = regex_unicode_version()

    p, s, n, not_n = (regex.compile(x) for x in (r"\p{P}", r"\p{S}", r"\p{N}", r"\P{N}"))
    intl = []
    for cp in range(MAX_CP):
        ch = chr(cp)
        is_p, is_s, is_n = bool(p.fullmatch(ch)), bool(s.fullmatch(ch)), bool(n.fullmatch(ch))
        assert is_n != bool(not_n.fullmatch(ch)), hex(cp)
        assert is_p + is_s + is_n <= 1, hex(cp)
        if cp in SURROGATES:
            assert not is_p, hex(cp)
            assert not is_s, hex(cp)
            assert not is_n, hex(cp)
        intl.append(PUNCT if is_p else SYMBOL if is_s else NUMBER if is_n else OTHER)

    is_zh = TokenizerZh._is_chinese_char
    zh = [int(cp not in SURROGATES and bool(is_zh(chr(cp)))) for cp in range(MAX_CP)]

    names = {PUNCT: "Punct", SYMBOL: "Symbol", NUMBER: "Number"}
    lines = [
        "// Derived from sacrebleu 2.6.0 (Apache-2.0), © Amazon.com, Inc. or its affiliates; "
        "modified.",
        "// @generated by generate_tables.py from sacrebleu "
        f"{sacrebleu_version} and regex {regex_version}; do not edit.",
        "//! Code point classes for the `intl` and `zh` tokenizers (generated).",
        "",
        "use super::tokenizers::IntlClass;",
        "",
        "/// The sacrebleu release the tables reproduce.",
        f'pub const SACREBLEU_VERSION: &str = "{sacrebleu_version}";',
        "/// The `regex` release whose `\\p{P}`, `\\p{S}` and `\\p{N}` the `intl` table records.",
        f'pub const REGEX_VERSION: &str = "{regex_version}";',
        "/// The Unicode version of that `regex` release (from its metadata).",
        f'pub const REGEX_UNICODE_VERSION: &str = "{unicode_version}";',
        "",
        "/// `(first, last, class)` runs of code points in `\\p{P}`, `\\p{S}` or `\\p{N}`,",
        "/// sorted and disjoint; every other code point is [`IntlClass::Other`].",
        "pub static INTL: &[(u32, u32, IntlClass)] = &[",
    ]
    lines += [f"    (0x{a:04X}, 0x{b:04X}, IntlClass::{names[c]})," for a, b, c in ranges(intl)]
    lines += [
        "];",
        "",
        "/// [`INTL`] for ASCII, indexed by code point.",
        "pub static INTL_ASCII: [IntlClass; 128] = [",
    ]
    lines += [f"    IntlClass::{names.get(c, 'Other')}," for c in intl[:128]]
    lines += [
        "];",
        "",
        "/// `(first, last)` runs of code points for which `TokenizerZh._is_chinese_char` is true.",
        "pub static ZH: &[(u32, u32)] = &[",
    ]
    lines += [f"    (0x{a:04X}, 0x{b:04X})," for a, b, _ in ranges(zh)]
    lines += ["];", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}: {len(ranges(intl))} intl runs, {len(ranges(zh))} zh runs")  # noqa: T201


if __name__ == "__main__":
    main()
