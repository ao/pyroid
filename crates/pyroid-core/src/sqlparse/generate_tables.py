# ruff: noqa: T201  (a build script that reports on stdout)
"""Generate `tables.rs`: the CPython `str` and `re` data pyroid.sqlparse needs, per Unicode version.

sqlparse 0.6.1 upper-cases every word to look it up in its keyword dictionaries
(`str.upper()`), formats with `str.upper/lower/capitalize`, and lexes with `re` patterns
compiled with `re.IGNORECASE | re.UNICODE`. Their answers depend on the running interpreter's
Unicode database, so every table here is read off CPython itself:

* `str.upper()`, `str.lower()` and `str.capitalize()` of each single character (full
  mappings, up to three characters), and the Cased / Case_Ignorable sets `str.lower()`'s
  final-sigma rule consults (probed through the rule itself);
* `re`'s IGNORECASE data: `_sre.unicode_tolower` (the simple lowercase mapping sre compares
  with), `_sre.unicode_iscased`, and `re._casefix._EXTRA_CASES` (the extra equivalences such
  as `i`/U+0131, `s`/U+017F).

The newest Unicode version is emitted in full; each older one as the entries that differ.

Usage (Linux or the dev container), one interpreter per supported Unicode version:

    for py in 3.11 3.12 3.13 3.14 3.15; do
        uv run --no-project -p $py python -I generate_tables.py dump /target/gen/sqlparse-$py.json
    done
    python3 -I generate_tables.py emit /target/gen/sqlparse-*.json
"""

from __future__ import annotations

import json
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAX_CP = 0x110000
VERSIONS = ["14.0.0", "15.0.0", "15.1.0", "16.0.0", "17.0.0"]
HEADER = (
    "// @generated by generate_tables.py -- do not edit by hand.\n"
    "// Character data read off CPython 3.11-3.15 (PSF-2.0).\n"
)
# Real surrogates are never in a Rust `char`; U+10F800.. stand for remapped surrogates.
FORBIDDEN = [(0xD800, 0xDFFF), (0x10F800, 0x10FFFF)]


def _ranges(pred) -> list[list[int]]:
    out: list[list[int]] = []
    start = None
    for cp in range(MAX_CP + 1):
        hit = cp < MAX_CP and pred(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append([start, cp - 1])
            start = None
    return out


def _final(s: str) -> bool:
    """Whether the U+03A3 at the end of `s` lowers to the final form."""
    return s.lower().endswith("ς")


def _cased(cp: int) -> bool:
    # str.lower() consults Cased only for characters that are not Case_Ignorable (the scan
    # skips those): in c + "Σ" the sigma is final iff c is not ignorable and cased.
    return _final(chr(cp) + "Σ")


def _case_ignorable(cp: int) -> bool:
    # in "A" + c + "Σ" the sigma is final iff c is ignorable (skipped, "A" is cased) or cased
    return _final("A" + chr(cp) + "Σ") and not _cased(cp)


def dump(path: str) -> None:
    import _sre
    from re import _casefix

    v = unicodedata.unidata_version
    assert v in VERSIONS, v
    upper: dict[int, list[int]] = {}
    lower: dict[int, list[int]] = {}
    title: dict[int, list[int]] = {}
    slower: dict[int, int] = {}
    for cp in range(MAX_CP):
        c = chr(cp)
        u = c.upper()
        if u != c:
            upper[cp] = [ord(x) for x in u]
        lo = c.lower()
        if lo != c and cp != 0x3A3:
            lower[cp] = [ord(x) for x in lo]
        t = c.capitalize()
        if t != c:
            title[cp] = [ord(x) for x in t]
        sl = _sre.unicode_tolower(cp)
        if sl != cp:
            slower[cp] = sl
    for m in (upper, lower, title):
        assert all(1 <= len(x) <= 3 for x in m.values())
    assert "\u03a3".lower() == "\u03c3"
    assert "A\u03a3".lower() == "a\u03c2"
    for lo, hi in FORBIDDEN:
        for m in (upper, lower, title, slower):
            assert not any(lo <= k <= hi for k in m)
    data = {
        "python": sys.version.split()[0],
        "unicode": v,
        "upper": {str(k): x for k, x in upper.items()},
        "lower": {str(k): x for k, x in lower.items()},
        "cased": _ranges(_cased),
        "case_ignorable": _ranges(_case_ignorable),
        "title": {str(k): x for k, x in title.items()},
        "slower": {str(k): x for k, x in slower.items()},
        "iscased": _ranges(_sre.unicode_iscased),
        "extra": {str(k): list(x) for k, x in _casefix._EXTRA_CASES.items()},
    }
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(json.dumps(data))
    print(f"wrote {path}: Python {data['python']}, Unicode {v}")


def _vname(v: str) -> str:
    return "V" + "_".join(v.split(".")[:2])


def _map_rows(m: dict[int, list[int]]) -> str:
    rows = []
    for k in sorted(m):
        x = m[k] + [0] * (3 - len(m[k]))
        rows.append(f"({k:#x}, {x[0]:#x}, {x[1]:#x}, {x[2]:#x})")
    return ", ".join(rows)


def emit(paths: list[str]) -> None:
    dumps = {}
    for p in paths:
        d = json.loads(Path(p).read_text())
        dumps[d["unicode"]] = d
    assert sorted(dumps) == VERSIONS, sorted(dumps)
    latest = dumps[VERSIONS[-1]]
    out = [HEADER]
    out.append(
        "//! CPython's per-character case data (see `generate_tables.py`). Each full table is\n"
        "//! Unicode 17.0's; the `*_DELTA_*` tables hold the entries where an older version\n"
        "//! differs (a character mapping to itself there is `(cp, cp, 0, 0)`).\n\n"
        "#![allow(clippy::unreadable_literal)]\n\n"
        "/// `(code point, mapped 1, 2, 3)`; unused slots are 0.\n"
        "pub(super) type Full = (u32, u32, u32, u32);\n\n"
    )
    for key, doc in (("upper", "str.upper()"), ("lower", "str.lower()"), ("title", "str.capitalize()")):
        base = {int(k): x for k, x in latest[key].items()}
        out.append(f"/// `{doc}` of one character (Unicode 17.0).\n")
        out.append(f"pub(super) static {key.upper()}: [Full; {len(base)}] = [{_map_rows(base)}];\n\n")
        for v in VERSIONS[:-1]:
            m = {int(k): x for k, x in dumps[v][key].items()}
            delta = {}
            for cp in set(m) | set(base):
                if m.get(cp, [cp]) != base.get(cp, [cp]):
                    delta[cp] = m.get(cp, [cp])
            out.append(
                f"pub(super) static {key.upper()}_DELTA_{_vname(v)[1:]}: [Full; {len(delta)}] = "
                f"[{_map_rows(delta)}];\n"
            )
        out.append("\n")
    base_l = {int(k): x for k, x in latest["slower"].items()}
    out.append("/// `_sre.unicode_tolower` (simple lowercase mapping, Unicode 17.0).\n")
    out.append(
        f"pub(super) static SLOWER: [(u32, u32); {len(base_l)}] = ["
        + ", ".join(f"({k:#x}, {base_l[k]:#x})" for k in sorted(base_l))
        + "];\n"
    )
    for v in VERSIONS[:-1]:
        m = {int(k): x for k, x in dumps[v]["slower"].items()}
        delta = {cp: m.get(cp, cp) for cp in set(m) | set(base_l) if m.get(cp, cp) != base_l.get(cp, cp)}
        out.append(
            f"pub(super) static SLOWER_DELTA_{_vname(v)[1:]}: [(u32, u32); {len(delta)}] = ["
            + ", ".join(f"({k:#x}, {delta[k]:#x})" for k in sorted(delta))
            + "];\n"
        )
    out.append("\n")
    for key, doc in (
        ("iscased", "`_sre.unicode_iscased`"),
        ("cased", "Cased (and not Case_Ignorable), for the final-sigma rule"),
        ("case_ignorable", "Case_Ignorable, for the final-sigma rule"),
    ):
        seen: dict[str, str] = {}
        for v in VERSIONS:
            rs = dumps[v][key]
            body = ", ".join(f"({a:#x}, {b:#x})" for a, b in rs)
            name = f"{key.upper()}_{_vname(v)[1:]}"
            if body in seen:
                out.append(f"pub(super) static {name}: &[(u32, u32)] = {seen[body]};\n")
            else:
                seen[body] = name
                out.append(f"/// {doc}, Unicode {v}.\n")
                out.append(f"pub(super) static {name}: &[(u32, u32)] = &[{body}];\n")
        out.append("\n")
    extras = {json.dumps(dumps[v]["extra"], sort_keys=True) for v in VERSIONS}
    assert len(extras) == 1, "re._casefix differs between versions"
    extra = {int(k): x for k, x in latest["extra"].items()}
    out.append("\n/// `re._casefix._EXTRA_CASES` (the same in every version): lowercase -> others.\n")
    rows = []
    for k in sorted(extra):
        x = extra[k] + [0] * (2 - len(extra[k]))
        assert len(extra[k]) <= 2
        rows.append(f"({k:#x}, {x[0]:#x}, {x[1]:#x})")
    out.append(f"pub(super) static EXTRA_CASES: [(u32, u32, u32); {len(extra)}] = [{', '.join(rows)}];\n")
    (HERE / "tables.rs").write_text("".join(out))
    print(f"wrote {HERE / 'tables.rs'}")


if __name__ == "__main__":
    if sys.argv[1] == "dump":
        dump(sys.argv[2])
    elif sys.argv[1] == "emit":
        emit(sys.argv[2:])
    else:
        raise SystemExit(__doc__)
