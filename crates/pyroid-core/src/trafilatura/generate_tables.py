"""Generate the static tables behind `pyroid_core::trafilatura`.

Every table is read off the running CPython (and jusText's stoplist files), not transcribed:

* per Unicode version: `str.isprintable()` ranges, `str.lower()` (full mappings, with the
  Cased / Case_Ignorable sets CPython's final-sigma rule consults), checked to agree with what
  the Rust side reuses from `crate::filters::unicode` (`str.isspace`, `re`'s `\\d` =
  `str.isdecimal`, decimal digits in runs of ten);
* version-independent (checked equal in every interpreter): the characters `re.IGNORECASE`
  matches for each ASCII letter, `str.splitlines()` boundaries, `html.unescape`'s tables;
* jusText 3.0.2's stoplists merged the way trafilatura.external.jt_stoplist_init and
  justext.core.define_stoplist merge them (lower-cased twice), checked equal in every version.

Usage (Linux or the dev container), one interpreter per supported Unicode version:

    for py in python3.11 python3.12 python3.13 python3.14 python3.15; do
        $py -I generate_tables.py dump STOPLIST_DIR /target/gen/$py.json
    done
    python3 -I generate_tables.py emit /target/gen/*.json

STOPLIST_DIR is `justext/stoplists` of an installed justext 3.0.2. `emit` writes tables.rs and
stoplist.txt next to this file.

trafilatura 1.11.0 reads its stoplist from `trafilatura/data/jt-stopwords-pickle.lzma`
instead; this checks it holds the same words as stoplist.txt (so 1.11.0 needs no data file of
its own):

    /target/venv-t111/bin/python -I generate_tables.py jt-pickle STOPLIST_DIR \\
        .../site-packages/trafilatura/data/jt-stopwords-pickle.lzma
"""

# ruff: noqa: T201  (a build script: it reports what it wrote on stdout)

from __future__ import annotations

import hashlib
import html
import html.entities
import json
import os
import re
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAX_CP = 0x110000
HEADER = (
    "// @generated by generate_tables.py -- do not edit by hand.\n"
    "// Derived from CPython (PSF-2.0) and jusText 3.0.2 (BSD-2-Clause) data; modified.\n"
)
VERSIONS = ["14.0.0", "15.0.0", "15.1.0", "16.0.0", "17.0.0"]


def ranges(pred) -> list[list[int]]:
    out: list[list[int]] = []
    start = None
    for cp in range(MAX_CP + 1):
        hit = cp < MAX_CP and pred(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append([start, cp - 1])
            start = None
    return out


def _final(s: str) -> bool:
    "Whether the U+03A3 at the end of s lowers to the final form."
    return s.lower().endswith("ς")


def cased(cp: int) -> bool:
    # str.lower() consults Cased only for characters that are not Case_Ignorable (the scan
    # skips those), so this is Cased and not Case_Ignorable, probed through the rule itself:
    # in c + "Σ" the sigma is final iff c is not ignorable and cased.
    return _final(chr(cp) + "Σ")


def case_ignorable(cp: int) -> bool:
    # in "A" + c + "Σ" the sigma is final iff c is ignorable (skipped, "A" is cased) or cased
    return _final("A" + chr(cp) + "Σ") and not cased(cp)


def dump(stoplist_dir: str, out: str) -> None:
    v = unicodedata.unidata_version
    assert v in VERSIONS, v
    space = [cp for cp in range(MAX_CP) if chr(cp).isspace()]
    assert space == [cp for cp in range(MAX_CP) if re.match(r"\s", chr(cp))]
    assert all(len(f"a{chr(cp)}b".split()) == 2 for cp in space)
    # \d is str.isdecimal, in runs of ten consecutive values
    dec = [cp for cp in range(MAX_CP) if chr(cp).isdecimal()]
    assert dec == [cp for cp in range(MAX_CP) if re.match(r"\d", chr(cp))]
    decset = set(dec)
    for cp in dec:
        start = cp
        while start - 1 in decset:
            start -= 1
        assert unicodedata.decimal(chr(cp)) == (cp - start) % 10, hex(cp)
        assert int(chr(cp)) == (cp - start) % 10
    # \w is isalnum() or "_"
    for cp in range(MAX_CP):
        c = chr(cp)
        assert bool(re.match(r"\w", c)) == (c.isalnum() or c == "_"), hex(cp)
    lower = {}
    for cp in range(MAX_CP):
        c = chr(cp)
        if cp != 0x3A3 and c.lower() != c:
            lower[cp] = c.lower()
    # every ASCII letter's IGNORECASE match set
    icase = {}
    for letter in "abcdefghijklmnopqrstuvwxyz":
        pat = re.compile(letter, re.IGNORECASE)
        icase[letter] = [cp for cp in range(MAX_CP) if pat.fullmatch(chr(cp))]
        # the upper-case pattern letter matches the same set
        assert all(re.fullmatch(letter.upper(), chr(cp), re.I) for cp in icase[letter])
        for cp in icase[letter]:
            # and a pattern made of one of those characters matches the letter back
            assert re.fullmatch(re.escape(chr(cp)), letter, re.I), (letter, hex(cp))
    lines = [cp for cp in range(MAX_CP) if len(f"a{chr(cp)}b".splitlines()) == 2]
    # jusText: union of get_stoplist(lang) for every language (each word lower-cased), lowered again
    words: set[str] = set()
    for name in sorted(os.listdir(stoplist_dir)):
        if name.endswith(".txt"):
            data = Path(stoplist_dir, name).read_bytes()
            words.update(w.decode("utf8").lower() for w in data.splitlines())
    words = {w.lower() for w in words}
    assert not any("\n" in w for w in words)
    stop = "".join(w + "\n" for w in sorted(words))
    rec = {
        "python": sys.version.split()[0],
        "unicode": v,
        "printable": ranges(lambda cp: chr(cp).isprintable()),
        "cased": ranges(cased),
        "case_ignorable": ranges(case_ignorable),
        "lower": {str(k): x for k, x in lower.items()},
        "space": space,
        "lines": lines,
        "icase": icase,
        "html5": sorted(html.entities.html5.items()),
        "invalid_charrefs": sorted(html._invalid_charrefs.items()),  # type: ignore[attr-defined]
        "invalid_codepoints": sorted(html._invalid_codepoints),  # type: ignore[attr-defined]
        "stoplist_sha256": hashlib.sha256(stop.encode()).hexdigest(),
        "stoplist": stop,
    }
    with open(out, "w", encoding="utf-8") as f:
        json.dump(rec, f)
    print(f"{sys.version.split()[0]} (Unicode {v}): {len(words)} stopwords -> {out}")


def esc(s: str) -> str:
    out = []
    for ch in s:
        cp = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= cp < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\u{{{cp:x}}}")
    return "".join(out)


def rs_ranges(name: str, rs: list[list[int]]) -> str:
    body = ", ".join(f"(0x{a:x}, 0x{b:x})" for a, b in rs)
    return f"pub(super) static {name}: [(u32, u32); {len(rs)}] = [{body}];\n"


def jt_pickle(stoplist_dir: str, pickle_path: str) -> None:
    """trafilatura 1.11.0 feeds jusText its own `data/jt-stopwords-pickle.lzma`; the words
    classify_paragraphs keeps from it (lower-cased) are stoplist.txt, and jusText's merged
    stoplists: both releases read the one file."""
    import lzma
    import pickle

    with lzma.open(pickle_path, "rb") as f:
        jt = pickle.load(f)  # trusted: the file shipped in the trafilatura 1.11.0 wheel
    from_pickle = {w.lower() for w in jt}
    words: set[str] = set()
    for name in sorted(os.listdir(stoplist_dir)):
        if name.endswith(".txt"):
            data = Path(stoplist_dir, name).read_bytes()
            words.update(w.decode("utf8").lower() for w in data.splitlines())
    words = {w.lower() for w in words}
    committed = set((HERE / "stoplist.txt").read_text(encoding="utf-8").split("\n")) - {""}
    assert from_pickle == words == committed, (len(from_pickle), len(words), len(committed))
    print(
        f"{type(jt).__name__} of {len(jt)} words in the pickle: {len(from_pickle)} lower-cased, "
        f"equal to jusText's merged stoplists and stoplist.txt"
    )


def emit(paths: list[str]) -> None:
    recs = {}
    for p in paths:
        with open(p, encoding="utf-8") as f:
            r = json.load(f)
        recs[r["unicode"]] = r
    assert sorted(recs) == VERSIONS, sorted(recs)
    first = recs[VERSIONS[0]]
    for key in (
        "space",
        "lines",
        "icase",
        "html5",
        "invalid_charrefs",
        "invalid_codepoints",
        "stoplist_sha256",
    ):
        for v in VERSIONS:
            assert recs[v][key] == first[key], (key, v)
    space = first["space"]
    want_space = [9, 10, 11, 12, 13, 28, 29, 30, 31, 32, 133, 160, 5760]
    want_space += [*range(0x2000, 0x200B), 0x2028, 0x2029, 0x202F, 0x205F, 0x3000]
    assert space == want_space, space
    assert first["lines"] == [10, 11, 12, 13, 28, 29, 30, 133, 0x2028, 0x2029], first["lines"]
    out = [HEADER, "//! Per-Unicode-version string tables and jusText's merged stoplist size.\n\n"]
    out.append("#![allow(clippy::unreadable_literal)]\n\n")
    # IGNORECASE: non-ASCII characters matching an ASCII letter
    extra = []
    for letter, cps in sorted(first["icase"].items()):
        want = {ord(letter), ord(letter.upper())}
        assert want <= set(cps), letter
        extra += [(cp, letter) for cp in cps if cp not in want]
    assert all(cp >= 0x80 for cp, _ in extra), extra
    body = ", ".join(f"(0x{cp:x}, b'{letter}')" for cp, letter in sorted(extra))
    out.append(
        "/// Non-ASCII characters `re.IGNORECASE` matches with an ASCII letter (same in every "
        "version).\n"
    )
    out.append(f"pub(super) static ICASE_EXTRA: [(u32, u8); {len(extra)}] = [{body}];\n\n")
    # str.lower(): one table, each entry with the first version it appears in
    all_cps = sorted({int(k) for v in VERSIONS for k in recs[v]["lower"]})
    entries = []
    for cp in all_cps:
        vals = [recs[v]["lower"].get(str(cp)) for v in VERSIONS]
        firstv = next(i for i, x in enumerate(vals) if x is not None)
        assert all(x is not None for x in vals[firstv:]), hex(cp)
        assert len(set(vals[firstv:])) == 1, hex(cp)
        if cp < 0x80:
            assert vals[firstv] == chr(cp).lower()
            continue
        entries.append((cp, vals[firstv], firstv))
    body = ", ".join(f'(0x{cp:x}, "{esc(s)}", {i})' for cp, s, i in entries)
    out.append("/// `str.lower()` of non-ASCII characters other than U+03A3, with the index (in\n")
    out.append("/// `UnicodeVersion` order, 0 = 14.0) of the first version that has the mapping.\n")
    out.append(f"pub(super) static LOWER: [(u32, &str, u8); {len(entries)}] = [{body}];\n\n")
    for key, doc in (
        ("printable", "`str.isprintable()`"),
        ("cased", "Cased (final-sigma rule)"),
        ("case_ignorable", "Case_Ignorable (final-sigma rule)"),
    ):
        # share identical tables between versions
        seen: dict[str, str] = {}
        for v in VERSIONS:
            name = f"{key.upper()}_{v.replace('.', '_')}"
            blob = json.dumps(recs[v][key])
            out.append(f"/// {doc}, Unicode {v} (CPython {recs[v]['python']}).\n")
            if blob in seen:
                out.append(f"pub(super) static {name}: &[(u32, u32)] = &{seen[blob]};\n")
            else:
                seen[blob] = name
                rs = recs[v][key]
                out.append(rs_ranges(name, rs))
        out.append("\n")
    ents = first["html5"]
    body = ", ".join(f'("{esc(k)}", "{esc(x)}")' for k, x in ents)
    out.append("/// `html.entities.html5`, sorted by name.\n")
    out.append(f"pub(super) static HTML5: [(&str, &str); {len(ents)}] = [{body}];\n")
    body = ", ".join(f'(0x{k:x}, "{esc(x)}")' for k, x in first["invalid_charrefs"])
    out.append("/// `html._invalid_charrefs`, sorted.\n")
    out.append(
        f"pub(super) static INVALID_CHARREFS: [(u32, &str); {len(first['invalid_charrefs'])}] "
        f"= [{body}];\n"
    )
    body = ", ".join(f"0x{c:x}" for c in first["invalid_codepoints"])
    out.append("/// `html._invalid_codepoints`, sorted.\n")
    out.append(
        f"pub(super) static INVALID_CODEPOINTS: [u32; {len(first['invalid_codepoints'])}] "
        f"= [{body}];\n"
    )
    (HERE / "tables.rs").write_text("".join(out), encoding="utf-8")
    (HERE / "stoplist.txt").write_text(first["stoplist"], encoding="utf-8")
    print(
        f"wrote tables.rs ({len(entries)} lower mappings, {len(ents)} entities) and stoplist.txt "
        f"({first['stoplist'].count(chr(10))} words, sha256 {first['stoplist_sha256'][:12]})"
    )


if __name__ == "__main__":
    if sys.argv[1] == "dump":
        dump(sys.argv[2], sys.argv[3])
    elif sys.argv[1] == "jt-pickle":
        jt_pickle(sys.argv[2], sys.argv[3])
    else:
        emit(sys.argv[2:])
