//! What differs between Trafilatura releases: tag lists, XPath sets and thresholds. The code
//! reads these through [`Profile`]; a release that also changes control flow adds a branch on
//! `Ctx::p` where it differs.

use super::Version;
use super::v1_11::xpaths as x111;
use super::xpaths::{self, XFirst, XList};
use crate::html::tree::{Name, names as t};

/// One Trafilatura release's settings.
#[derive(Debug)]
pub struct Profile {
    /// settings.MANUALLY_CLEANED (in order).
    pub manually_cleaned: &'static [Name],
    /// settings.MANUALLY_STRIPPED.
    pub manually_stripped: &'static [Name],
    /// settings.CUT_EMPTY_ELEMS.
    pub cut_empty_elems: &'static [Name],
    /// settings.TAG_CATALOG.
    pub tag_catalog: &'static [Name],
    /// settings.MIN_DUPLICATE_LENGTH.
    pub min_duplicate_length: usize,
    /// settings.DEDUPE_SCAN_CAP.
    pub dedupe_scan_cap: usize,
    /// utils.LINK_FARM_RATIO.
    pub link_farm_ratio: f64,
    /// external.JUSTEXT_OVERRIDE_RATIO.
    pub justext_override_ratio: usize,
    /// core.ESCALATION_MAX_LENGTH / _PAGE_SHARE / _ACCEPT_RATIO / _JUSTEXT_RATIO.
    pub escalation_max_length: usize,
    pub escalation_page_share: f64,
    pub escalation_accept_ratio: f64,
    pub escalation_justext_ratio: f64,
    /// baseline._MIN_CONTENT_LENGTH.
    pub baseline_min_content: usize,
    pub body_xpath: &'static [XFirst],
    pub comments_xpath: &'static [XFirst],
    pub raw_tree_prune: XList,
    pub remove_comments: XList,
    pub remove_comments_and_lists: XList,
    pub overall_discard: XList,
    pub teaser_discard: XList,
    pub precision_discard: XList,
    pub discard_image_elements: XList,
    pub comments_discard: XList,
}

