"""Generate `tables.rs`: langdetect 1.0.9's character tables and Python's `str.isupper`.

langdetect's n-gram extraction maps every character through `NGram.normalize` and
decides "capital words" with `str.isupper()`, whose answer depends on the Unicode database
of the running interpreter. Both are dumped from the real code by testing every code point
(the tables are derived from what the functions return, not from reading their source),
then written as ranges; `isupper` tables identical in several Unicode versions are emitted
once.

Usage (Linux or a Linux container; one interpreter per Unicode version, langdetect 1.0.9
installed in the interpreter that runs `emit`):

    for v in 3.11 3.12 3.13 3.14 3.15; do
        uv run --no-project -p $v python -I generate_tables.py dump /tmp/gen/$v.json
    done
    python generate_tables.py emit /tmp/gen/*.json

`python generate_tables.py python` (langdetect 1.0.9 installed) writes the string tables of
langdetect's `NGram` (`CJK_CLASS`, `NORMALIZED_VI_CHARS`, ...) to
`python/pyroid/langdetect/utils/_tables.py`.
"""

from __future__ import annotations

import json
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = (
    "// @generated by generate_tables.py -- do not edit by hand.\n"
    "// Derived from langdetect 1.0.9 (Apache-2.0), © Cybozu Labs, Inc. and Michal Danilak;\n"
    "// modified.\n"
)
MAX_CP = 0x110000
VERSIONS = ["14.0.0", "15.0.0", "15.1.0", "16.0.0", "17.0.0"]


def _ranges(flags: list[bool]) -> list[tuple[int, int]]:
    """Inclusive ranges of the code points whose flag is set."""
    out: list[tuple[int, int]] = []
    start = None
    for cp, flag in enumerate(flags):
        if flag and start is None:
            start = cp
        elif not flag and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, len(flags) - 1))
    return out


def dump(out: str) -> None:
    flags = [chr(cp).isupper() for cp in range(MAX_CP)]
    data = {"unicode": unicodedata.unidata_version, "python": sys.version, "upper": _ranges(flags)}
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text(json.dumps(data))
    print(f"{out}: Unicode {data['unicode']}, {len(data['upper'])} ranges")


def _normalize_runs() -> list[tuple[int, int, int, int]]:
    """`NGram.normalize` as runs `(start, end, kind, value)`.

    kind 0: identity; 1: every code point maps to `value`; 2: a single code point maps to
    `value` (start == end).
    """
    from langdetect.utils.ngram import NGram

    mapped = [ord(NGram.normalize(chr(cp))) for cp in range(MAX_CP)]
    runs: list[tuple[int, int, int, int]] = []
    cp = 0
    while cp < MAX_CP:
        m = mapped[cp]
        end = cp
        if m == cp:
            while end + 1 < MAX_CP and mapped[end + 1] == end + 1:
                end += 1
            runs.append((cp, end, 0, 0))
        else:
            while end + 1 < MAX_CP and mapped[end + 1] == m and m != end + 1:
                end += 1
            runs.append((cp, end, 1 if end > cp else 2, m))
        cp = end + 1
    # Sanity: nothing outside the BMP changes, every result is in the BMP.
    assert all(k == 0 for s, _, k, _ in runs if s >= 0x10000), "non-identity above the BMP"
    assert all(v < 0x10000 for _, _, k, v in runs if k), "a result outside the BMP"
    return runs


def _vi_tables() -> tuple[list[int], list[int], list[list[int]]]:
    from langdetect.utils.ngram import NGram

    base = [ord(c) for c in NGram.TO_NORMALIZE_VI_CHARS]
    marks = [ord(c) for c in NGram.DMARK_CLASS]
    table = [[ord(c) for c in row] for row in NGram.NORMALIZED_VI_CHARS]
    assert len(set(base)) == len(base)
    assert len(set(marks)) == len(marks)
    assert all(len(row) == len(base) for row in table)
    assert len(table) == len(marks)
    # The regex is a plain pair of character classes: check every pair, and a few non-pairs.
    for i, b in enumerate(base):
        for j, m in enumerate(marks):
            assert NGram.normalize_vi(chr(b) + chr(m)) == chr(table[j][i])
    assert NGram.normalize_vi("à̀") == "à̀"
    return base, marks, table


def _fmt_pairs(name: str, ty: str, items: list[str], per_line: int = 6) -> str:
    lines = [f"pub static {name}: &[{ty}] = &["]
    lines += ["    " + " ".join(items[i : i + per_line]) for i in range(0, len(items), per_line)]
    lines.append("];\n")
    return "\n".join(lines)


def emit(dumps: list[str]) -> None:
    import langdetect
    from langdetect.detector import Detector

    by_version: dict[str, list[list[int]]] = {}
    for path in dumps:
        data = json.loads(Path(path).read_text())
        by_version[data["unicode"]] = data["upper"]
    missing = [v for v in VERSIONS if v not in by_version]
    assert not missing, f"no dump for Unicode {missing}"
    runs = _normalize_runs()
    base, marks, table = _vi_tables()
    # The URL and mail patterns the hand-written matchers in text.rs reproduce.
    assert Detector.URL_RE.pattern == r"https?://[-_.?&~;+=/#0-9A-Za-z]{1,2076}"
    assert (
        Detector.MAIL_RE.pattern
        == r"[-_.0-9A-Za-z]{1,64}@[-_0-9A-Za-z]{1,255}[-_.0-9A-Za-z]{1,255}"
    )
    out = [HEADER]
    out.append(f"// langdetect {getattr(langdetect, '__version__', '1.0.9')}; NGram.normalize\n")
    out.append(
        "/// `NGram.normalize` as `(start, end, kind, value)`: kind 0 keeps the code point,\n"
        "/// 1 maps the whole run to `value`, 2 maps the single code point to `value`.\n"
    )
    out.append(
        _fmt_pairs(
            "NORMALIZE_RUNS",
            "(u32, u32, u8, u32)",
            [f"(0x{s:X}, 0x{e:X}, {k}, 0x{v:X})," for s, e, k, v in runs],
            per_line=3,
        )
    )
    out.append(f"/// `NGram.TO_NORMALIZE_VI_CHARS`.\npub static VI_BASE: [u32; {len(base)}] = [")
    out.append(", ".join(f"0x{c:X}" for c in base) + "];\n")
    out.append(f"/// `NGram.DMARK_CLASS`.\npub static VI_MARKS: [u32; {len(marks)}] = [")
    out.append(", ".join(f"0x{c:X}" for c in marks) + "];\n")
    out.append(
        f"/// `NGram.NORMALIZED_VI_CHARS[mark][base]`.\n"
        f"pub static VI_TABLE: [[u32; {len(base)}]; {len(marks)}] = [\n"
    )
    out += ["    [" + ", ".join(f"0x{c:X}" for c in row) + "],\n" for row in table]
    out.append("];\n\n")
    # isupper: one table per distinct content.
    names: dict[str, str] = {}
    for version in VERSIONS:
        ranges = by_version[version]
        key = json.dumps(ranges)
        if key in names:
            continue
        name = "UPPER_" + version.replace(".", "_")
        names[key] = name
        out.append(f"/// `str.isupper()` for Unicode {version}, inclusive ranges.\n")
        out.append(_fmt_pairs(name, "(u32, u32)", [f"(0x{s:X}, 0x{e:X})," for s, e in ranges], 6))
    out.append("/// The Unicode versions with an `isupper` table, and their table.\n")
    out.append("pub static UPPER_TABLES: &[(&str, &[(u32, u32)])] = &[\n")
    out += [f'    ("{v}", {names[json.dumps(by_version[v])]}),\n' for v in VERSIONS]
    out.append("];\n")
    target = HERE / "tables.rs"
    target.write_text("".join(out))
    print(f"wrote {target}: {len(runs)} normalize runs, {len(set(names.values()))} isupper tables")


def _py_str(s: str, indent: str, lead: int) -> str:
    """`s` as an ASCII Python literal (non-ASCII as \\uXXXX) that fits 100 columns after
    `lead` characters, split into lines at `indent` if it does not."""
    parts = [c if 0x20 <= ord(c) < 0x7F and c not in '"\\' else f"\\u{ord(c):04x}" for c in s]
    if lead + len("".join(parts)) + 3 <= 100:
        return '"' + "".join(parts) + '"'
    width = 100 - len(indent) - 2
    lines: list[str] = []
    line = ""
    for p in parts:
        if len(line) + len(p) > width:
            lines.append(line)
            line = ""
        line += p
    lines.append(line)
    return "(\n" + "".join(f'{indent}"{x}"\n' for x in lines) + indent[:-4] + ")"


def emit_python() -> None:
    """Write `python/pyroid/langdetect/utils/_tables.py`: NGram's string tables."""
    from langdetect.utils.ngram import NGram

    target = HERE.parents[3] / "python" / "pyroid" / "langdetect" / "utils" / "_tables.py"
    generator = "crates/pyroid-core/src/langdetect/generate_tables.py"
    out = [
        f"# @generated by {generator} -- do not edit by hand.\n"
        "# Derived from langdetect 1.0.9 (Apache-2.0), © Cybozu Labs, Inc. and Michal Danilak;\n"
        "# modified.\n",
        '"""The ``NGram`` tables of langdetect 1.0.9 (its ``messages.properties``)."""\n',
    ]
    out.extend(
        f"\n{name} = {_py_str(getattr(NGram, name), '    ', len(name) + 3)}\n"
        for name in ("LATIN1_EXCLUDED", "TO_NORMALIZE_VI_CHARS", "DMARK_CLASS")
    )
    for name in ("NORMALIZED_VI_CHARS", "CJK_CLASS"):
        rows = getattr(NGram, name)
        out.append(f"\n{name} = [\n")
        out.extend(f"    {_py_str(row, '        ', 4)},\n" for row in rows)
        out.append("]\n")
    target.write_text("".join(out), encoding="utf-8")
    print(
        f"wrote {target}: {len(NGram.CJK_CLASS)} CJK classes, {len(NGram.CJK_MAP)} CJK_MAP entries"
    )


if __name__ == "__main__":
    if sys.argv[1:2] == ["dump"]:
        dump(sys.argv[2])
    elif sys.argv[1:2] == ["emit"]:
        emit(sys.argv[2:])
    elif sys.argv[1:2] == ["python"]:
        emit_python()
    else:
        sys.exit(__doc__)
