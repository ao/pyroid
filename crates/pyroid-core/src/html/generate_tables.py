"""Generate the static tables behind `pyroid_core::html` from the libxml2 2.14.6 sources.

Derived from libxml2 2.14.6 (MIT), (c) Daniel Veillard and contributors; modified.

Reads, from an unpacked libxml2-2.14.6 source tree (the release tarball from
https://download.gnome.org/sources/libxml2/2.14/):

* HTMLparser.c: `html40ElementTable` (name, `empty`, `dataMode`), `htmlStartClose` and
  `htmlEndPriority`, plus the `DATA_*` constants;
* HTMLtree.c: `htmlBooleanAttrs`;
* html5ent.inc: `htmlEntAlpha`, `htmlEntValues` and `htmlEntStrings`, copied as they are
  (the layout `htmlFindEntityPrefix` reads).

and writes `tables.rs` and `entities.rs` next to this script. Each generated file records the
SHA-256 of the source files it came from. The tables are emitted in their C order: libxml2
looks elements and start-close pairs up with `bsearch`, and `tables.rs` keeps that order so a
test can check it.

Usage (in the dev container):

    python generate_tables.py /path/to/libxml2-2.14.6
"""

from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

VERSION = "2.14.6"
HERE = Path(__file__).resolve().parent
HEADER = (
    "// @generated by generate_tables.py -- do not edit by hand.\n"
    "// Derived from libxml2 2.14.6 (MIT), © Daniel Veillard and contributors; modified.\n"
)


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def c_array_body(src: str, decl: str) -> str:
    """The text between `decl ... = {` and the matching `};`."""
    start = src.index(decl)
    open_brace = src.index("{", start)
    end = src.index("\n};", open_brace)
    return src[open_brace + 1 : end]


TOKEN = re.compile(r'"(?:[^"\\]|\\.)*"|[^,\s]+')


def elements(src: str) -> list[tuple[str, bool, str]]:
    body = c_array_body(src, "html40ElementTable[] =")
    out = []
    for entry in re.findall(r"\{(.*?)\}", body, re.S):
        toks = TOKEN.findall(entry)
        if len(toks) != 15:
            raise SystemExit(f"unexpected html40ElementTable entry: {entry!r}")
        name = toks[0].strip('"')
        empty = int(toks[4])
        data_mode = toks[14]
        if data_mode != "0" and not data_mode.startswith("DATA_"):
            raise SystemExit(f"unexpected dataMode {data_mode!r} for {name}")
        out.append((name, bool(empty), data_mode))
    return out


def data_modes(src: str) -> dict[str, int]:
    return {m[1]: int(m[2]) for m in re.finditer(r"#define (DATA_\w+)\s+(\d+)", src)}


def start_close(src: str) -> list[tuple[str, str]]:
    body = c_array_body(src, "htmlStartClose[] =")
    pairs = re.findall(r'\{\s*"([^"]+)",\s*"([^"]+)"\s*\}', body)
    if body.count("{") != len(pairs):
        raise SystemExit("unexpected htmlStartClose entry")
    return pairs


def end_priority(src: str) -> tuple[list[tuple[str, int]], int]:
    body = c_array_body(src, "htmlEndPriority[] =")
    named = [(n, int(p)) for n, p in re.findall(r'\{\s*"(\w+)",\s*(\d+)\s*\}', body)]
    default = re.search(r"\{\s*NULL,\s*(\d+)\s*\}", body)
    if default is None or body.count("{") != len(named) + 1:
        raise SystemExit("unexpected htmlEndPriority entry")
    return named, int(default[1])


def boolean_attrs(src: str) -> list[str]:
    body = c_array_body(src, "htmlBooleanAttrs[] =")
    if not body.rstrip().endswith("NULL"):
        raise SystemExit("htmlBooleanAttrs does not end with NULL")
    return re.findall(r'"([^"]+)"', body)


def c_bytes(src: str, decl: str) -> list[int]:
    """Integer and character-literal elements of a C array."""
    body = c_array_body(src, decl)
    out = []
    for tok in re.findall(r"'(?:[^'\\]|\\.)'|\d+", body):
        if tok.startswith("'"):
            ch = tok[1:-1]
            if ch.startswith("\\"):
                ch = {"\\'": "'", "\\\\": "\\", '\\"': '"'}[ch]
            out.append(ord(ch))
        else:
            out.append(int(tok))
    declared = int(re.search(re.escape(decl.split("[")[0]) + r"\[(\d+)\]", src)[1])
    if len(out) != declared:
        raise SystemExit(f"{decl}: {len(out)} values, declared {declared}")
    return out


def rust_array(name: str, ty: str, values: list[int], doc: str) -> str:
    lines = [f"/// {doc}", f"pub(super) static {name}: [{ty}; {len(values)}] = ["]
    row: list[str] = []
    width = 4
    for v in values:
        s = f"{v},"
        if width + len(s) + 1 > 100:
            lines.append("    " + " ".join(row))
            row, width = [], 4
        row.append(s)
        width += len(s) + 1
    if row:
        lines.append("    " + " ".join(row))
    lines.append("];")
    return "\n".join(lines) + "\n"


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    root = Path(sys.argv[1])
    parser_c = root / "HTMLparser.c"
    tree_c = root / "HTMLtree.c"
    ent_inc = root / "html5ent.inc"
    news = (root / "NEWS").read_text(encoding="utf-8")
    first_release = re.search(r"^v(\d+\.\d+\.\d+):", news, re.M)
    if first_release is None or first_release[1] != VERSION:
        raise SystemExit(f"expected libxml2 {VERSION} sources (NEWS), got {first_release}")

    psrc = parser_c.read_text(encoding="utf-8")
    tsrc = tree_c.read_text(encoding="utf-8")
    esrc = ent_inc.read_text(encoding="utf-8")
    modes = data_modes(psrc)
    elems = elements(psrc)
    pairs = start_close(psrc)
    prio, prio_default = end_priority(psrc)
    booleans = boolean_attrs(tsrc)

    t = [HEADER]
    t.append(
        f"//! Tables from libxml2 {VERSION}: `html40ElementTable`, `htmlStartClose` and\n"
        "//! `htmlEndPriority` (HTMLparser.c) and `htmlBooleanAttrs` (HTMLtree.c), with the\n"
        "//! columns the parser reads, in the C order.\n"
        "//!\n"
        f"//! HTMLparser.c sha256 {sha256(parser_c)}\n"
        f"//! HTMLtree.c   sha256 {sha256(tree_c)}\n\n"
    )
    for k in ("DATA_RCDATA", "DATA_RAWTEXT", "DATA_PLAINTEXT", "DATA_SCRIPT", "DATA_SCRIPT_ESC1",
              "DATA_SCRIPT_ESC2"):
        t.append(f"pub(super) const {k}: u8 = {modes[k]};\n")
    t.append(
        "\n/// `html40ElementTable`: (name, `empty`, `dataMode`). The other columns only matter\n"
        "/// for libxml2's serializer and validity checks.\n"
        f"pub(super) static ELEMENTS: [(&str, bool, u8); {len(elems)}] = [\n"
    )
    for name, empty, mode in elems:
        t.append(f'    ("{name}", {"true" if empty else "false"}, {mode if mode != "0" else 0}),\n')
    t.append("];\n\n")
    t.append(
        "/// `htmlStartClose`: (old, new) when a start tag `new` closes an open `old`.\n"
        f"pub(super) static START_CLOSE: [(&str, &str); {len(pairs)}] = [\n"
    )
    for old, new in pairs:
        t.append(f'    ("{old}", "{new}"),\n')
    t.append("];\n\n")
    t.append(
        "/// `htmlEndPriority`: which open elements an end tag may close.\n"
        f"pub(super) static END_PRIORITY: [(&str, i32); {len(prio)}] = [\n"
    )
    for name, p in prio:
        t.append(f'    ("{name}", {p}),\n')
    t.append("];\n\n")
    t.append("/// `htmlEndPriority`'s default, for every other name.\n")
    t.append(f"pub(super) const END_PRIORITY_DEFAULT: i32 = {prio_default};\n\n")
    t.append(
        "/// `htmlBooleanAttrs`: attributes whose value is their name when none is given.\n"
        f"pub(super) static BOOLEAN_ATTRS: [&str; {len(booleans)}] = [\n"
    )
    # Filled rows, as rustfmt lays out short string literals.
    row = "   "
    for b in booleans:
        item = f' "{b}",'
        if len(row) + len(item) > 99:
            t.append(row + "\n")
            row = "   "
        row += item
    t.append(row + "\n];\n")
    (HERE / "tables.rs").write_text("".join(t), encoding="utf-8")

    e = [HEADER]
    e.append(
        f"//! Named character references: `htmlEntAlpha`, `htmlEntValues` and `htmlEntStrings`\n"
        f"//! from libxml2 {VERSION} html5ent.inc, as they are (the layout `htmlFindEntityPrefix`\n"
        "//! reads: per first letter a range of `htmlEntValues`, which point into\n"
        "//! `htmlEntStrings` at a length byte with flag bits, the rest of the name, and the\n"
        "//! replacement or a sub-table).\n"
        "//!\n"
        f"//! html5ent.inc sha256 {sha256(ent_inc)}\n\n"
    )
    e.append(rust_array("ENT_ALPHA", "u8", c_bytes(esrc, "htmlEntAlpha["), "`htmlEntAlpha`."))
    e.append("\n")
    e.append(rust_array("ENT_VALUES", "u16", c_bytes(esrc, "htmlEntValues["), "`htmlEntValues`."))
    e.append("\n")
    e.append(rust_array("ENT_STRINGS", "u8", c_bytes(esrc, "htmlEntStrings["), "`htmlEntStrings`."))
    (HERE / "entities.rs").write_text("".join(e), encoding="utf-8")
    print(f"tables.rs: {len(elems)} elements, {len(pairs)} start-close pairs; entities.rs written")


if __name__ == "__main__":
    main()
