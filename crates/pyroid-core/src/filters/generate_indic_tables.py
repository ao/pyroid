"""Generate `indic_tables.rs`, the tables behind `filters::indic` and `filters::whitespace`.

Everything is read from the libraries themselves, never retyped:

* `numeric`: `chr(c).isnumeric()` for every code point, one dump per CPython
  (one per Unicode version), like `generate_unicode_tables.py` does for the
  other predicates. indic-nlp's `sentence_split` tests it.
* indic-nlp-library (0.92): the character classes of `trivial_tokenize`'s two
  punctuation patterns and of `sentence_split`'s delimiter patterns (by
  matching every code point), `langinfo` (script ranges, danda languages),
  the non-breaking phrases of `is_acronym_abbvr` (from its source, with `ast`),
  and the Sinhala-to-Devanagari map. The regexes that are ported by hand are
  asserted to be the ones the port was written for.
* urduhack (1.0.3) `tokenization/eos.py`: the two word lists of its rule-based
  sentence splitter (indic-nlp's `sentence_split` for `ur`). eos.py is loaded
  on its own: importing the `urduhack` package needs TensorFlow.
* `regex` (2026.9.29): `\\p{Lu}` and the classes of datatrove's
  `WhitespaceTokenizer` sentence pattern, again by matching every code point.
* datatrove (0.10.1): which language codes use `IndicNLPTokenizer` (and with
  which indic-nlp language) and which use `WhitespaceTokenizer`.

Usage (inside the pyroid-dev container; never on the host):

    # 1. one isnumeric dump per interpreter (no dependencies needed)
    for v in 311 312 313 314 315; do
        /target/venv-$v/bin/python generate_indic_tables.py dump /target/gen-indic/$v.json
    done
    # 2. write indic_tables.rs next to this script, from a venv with
    #    datatrove==0.10.1, indic-nlp-library, regex==2026.9.29
    python generate_indic_tables.py emit --eos URDUHACK/tokenization/eos.py /target/gen-indic/*.json
"""

# ruff: noqa: T201  (a build script: it reports what it wrote on stdout)

from __future__ import annotations

import ast
import importlib.util
import inspect
import json
import re
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = (
    "// @generated by generate_indic_tables.py -- do not edit by hand.\n"
    "// Derived from indic-nlp-library 0.92 (MIT), (c) Anoop Kunchukuttan, urduhack\n"
    "// 1.0.3 (MIT), (c) Urdu Hack, and datatrove 0.10.1 (Apache-2.0), (c) HuggingFace.\n"
    "// Read from CPython, indic-nlp-library, urduhack, regex and datatrove.\n"
)
MAX_CP = 0x110000

# unicodedata.unidata_version -> `crate::ftfy::UnicodeVersion` variant.
VERSIONS = {
    "14.0.0": "V14_0",
    "15.0.0": "V15_0",
    "15.1.0": "V15_1",
    "16.0.0": "V16_0",
    "17.0.0": "V17_0",
}

# The hand-ported patterns, exactly as the port reads them.
NUM_SEQ = r"([0-9]+ [,.:/] )+[0-9]+"
TOKENIZERS = ("IndicNLPTokenizer", "WhitespaceTokenizer")


def _chars():
    for cp in range(MAX_CP):
        if not 0xD800 <= cp < 0xE000:
            yield cp, chr(cp)


def _ranges(hits) -> list[list[int]]:
    out: list[list[int]] = []
    for cp in sorted(hits):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def dump(path: str) -> None:
    hits = [cp for cp, ch in _chars() if ch.isnumeric()]
    data = {
        "python": sys.version.split()[0],
        "unicode": unicodedata.unidata_version,
        "numeric": _ranges(hits),
    }
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(json.dumps(data, sort_keys=True))
    print(f"wrote {path}: Python {data['python']}, Unicode {data['unicode']}, {len(hits)} numeric")


# --------------------------------------------------------------------------
# emit
# --------------------------------------------------------------------------


def _class(pattern) -> list[int]:
    """Code points a one-character pattern matches."""
    return [cp for cp, ch in _chars() if pattern.fullmatch(ch)]


def _rs_char(cp: int) -> str:
    return f"'\\u{{{cp:x}}}'"


def _rs_str(s: str) -> str:
    return '"' + "".join(f"\\u{{{ord(c):x}}}" for c in s) + '"'


def _emit_chars(name: str, doc: str, cps: list[int], vis: str = "pub(super)") -> str:
    body = ", ".join(_rs_char(c) for c in sorted(cps))
    return f"/// {doc}\n{vis} static {name}: &[char] = &[{body}];\n"


def _emit_ranges(name: str, doc: str, ranges, vis: str = "pub(super)") -> str:
    body = ", ".join(f"(0x{a:x}, 0x{b:x})" for a, b in ranges)
    return f"/// {doc}\n{vis} static {name}: [(u32, u32); {len(ranges)}] = [{body}];\n"


def _ascii_mask(ranges) -> int:
    mask = 0
    for a, b in ranges:
        for cp in range(a, min(b, 0x7F) + 1):
            mask |= 1 << cp
    return mask


def _set_literal(func, name: str) -> list[str]:
    """The string elements of the set literal assigned to `name` in `func`."""
    tree = ast.parse(inspect.getsource(func).lstrip())
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == name for t in node.targets
        ):
            return sorted(ast.literal_eval(node.value))
    raise SystemExit(f"no `{name} = {{...}}` in {func.__qualname__}")


def _load_eos(path: str):
    spec = importlib.util.spec_from_file_location("urduhack_eos", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def emit(eos_path: str, paths: list[str]) -> None:
    import regex
    from datatrove.utils import word_tokenizers as dwt
    from datatrove.utils.text import TERMINAL_PUNCTUATION
    from indicnlp import langinfo
    from indicnlp.tokenize import indic_tokenize, sentence_tokenize
    from indicnlp.transliterate.sinhala_transliterator import SinhalaDevanagariTransliterator
    from indicnlp.transliterate.unicode_transliterate import UnicodeIndicTransliterator

    dumps = [json.loads(Path(p).read_text()) for p in paths]
    dumps.sort(key=lambda d: [int(x) for x in d["unicode"].split(".")])
    got = [d["unicode"] for d in dumps]
    assert got == list(VERSIONS), f"need one dump per version {list(VERSIONS)}, got {got}"

    out = [
        HEADER,
        "//! Tables for `filters::indic` (indic-nlp-library `trivial_tokenize` /\n",
        "//! `sentence_split`, urduhack's sentence splitter) and `filters::whitespace`\n",
        "//! (datatrove `WhitespaceTokenizer`'s sentence regex).\n\n",
        "#![allow(clippy::unreadable_literal)]\n\n",
        "use super::Script;\n",
        "use crate::ftfy::UnicodeVersion;\n\n",
    ]

    # ---- isnumeric, per version
    masks = {_ascii_mask(d["numeric"]) for d in dumps}
    assert masks == {0x3FF << 0x30}, "isnumeric on ASCII is not exactly 0-9"
    out.append("// ---- `str.isnumeric()`, per Unicode version ----\n\n")
    groups: dict[tuple, list[dict]] = {}
    for d in dumps:
        key = tuple((max(a, 0x80), b) for a, b in d["numeric"] if b >= 0x80)
        groups.setdefault(key, []).append(d)
    arms = []
    for table, ds in groups.items():
        tag = ds[0]["unicode"].removesuffix(".0").replace(".", "_")
        used = ", ".join(f"Unicode {d['unicode']} (CPython {d['python']})" for d in ds)
        out.append(_emit_ranges(f"NUMERIC_{tag}", f"`str.isnumeric()` above ASCII: {used}.", table))
        pats = " | ".join(f"UnicodeVersion::{VERSIONS[d['unicode']]}" for d in ds)
        arms.append(f"        {pats} => &NUMERIC_{tag},\n")
    out.append("\n/// The `NUMERIC_*` table for `v` (ASCII: only `0`-`9` are numeric).\n")
    out.append("pub(super) fn numeric(v: UnicodeVersion) -> &'static [(u32, u32)] {\n")
    out.append("    match v {\n" + "".join(arms) + "    }\n}\n\n")

    # ---- trivial_tokenize
    assert indic_tokenize.pat_num_seq.pattern == NUM_SEQ, indic_tokenize.pat_num_seq.pattern
    indic_punct = _class(indic_tokenize.triv_tokenizer_indic_pat)
    urdu_punct = _class(indic_tokenize.triv_tokenizer_urdu_pat)
    out.append("// ---- indic-nlp-library `trivial_tokenize` ----\n\n")
    out.append(_emit_chars("INDIC_PUNCT", "`triv_tokenizer_indic_pat`'s class.", indic_punct))
    out.append(_emit_chars("URDU_PUNCT", "`triv_tokenizer_urdu_pat`'s class.", urdu_punct))

    # ---- sentence_split
    st = sentence_tokenize
    danda = _class(st.DELIM_PAT_DANDA)
    no_danda = _class(st.DELIM_PAT_NO_DANDA)
    contains = _class(st.CONTAINS_DANDA)
    assert contains == [0x964, 0x965], contains
    assert not st.DELIM_PAT_DANDA.search(".")
    assert st.DELIM_PAT_NO_DANDA.search(".")
    out.append("\n// ---- indic-nlp-library `sentence_split` ----\n\n")
    out.append(_emit_chars("DELIM_DANDA", "`DELIM_PAT_DANDA`'s class.", danda))
    out.append(_emit_chars("DELIM_NO_DANDA", "`DELIM_PAT_NO_DANDA`'s class.", no_danda))
    ack = _set_literal(st.is_acronym_abbvr, "ack_chars")
    assert all(st.is_acronym_abbvr(a, "hi") for a in ack)
    assert all(all(0x900 <= ord(c) <= 0x96F for c in a) for a in ack), "ack set leaves 0x900..0x96F"
    body = ", ".join(_rs_str(a) for a in sorted(ack, key=lambda s: s.encode()))
    out.append(
        "/// `is_acronym_abbvr`'s non-breaking phrases (Devanagari), sorted by UTF-8 bytes.\n"
        f"pub(super) static ACRONYMS: &[&str] = &[{body}];\n"
    )
    sinh = SinhalaDevanagariTransliterator.sinhala_devnag_map
    assert all(len(k) == 1 and len(v) == 1 for k, v in sinh.items())
    body = ", ".join(f"({_rs_char(ord(k))}, {_rs_char(ord(v))})" for k, v in sorted(sinh.items()))
    out.append(
        "/// `SinhalaDevanagariTransliterator.sinhala_devnag_map`, sorted.\n"
        f"pub(super) static SINHALA_TO_DEVANAGARI: &[(char, char)] = &[{body}];\n"
    )
    assert langinfo.COORDINATED_RANGE_START_INCLUSIVE == 0
    assert langinfo.COORDINATED_RANGE_END_INCLUSIVE == 0x6F
    assert langinfo.SCRIPT_RANGES["hi"][0] == 0x900
    # A check of the transliteration rule the port uses, on every character
    # of every script (target "hi", so no Tamil correction).
    for lang, (base, _) in langinfo.SCRIPT_RANGES.items():
        for cp in [*range(0x900, 0xE00), 0x41, 0x2E]:
            c = chr(cp)
            want = UnicodeIndicTransliterator.transliterate(c, lang, "hi")
            if lang == "si":
                c2 = sinh.get(c, c)
                off = ord(c2) - 0x900
            else:
                c2, off = c, cp - base
            exp = chr(0x900 + off) if 0 <= off <= 0x6F and c2 not in "।॥" else c2
            assert want == exp, (lang, hex(cp), want, exp)

    # ---- datatrove's assignments
    assigned = dwt.load_tokenizer_assignments()
    langs = {name: [] for name in TOKENIZERS}
    for code, factory in sorted(assigned.items()):
        cls, arg = factory.args
        if cls in langs:
            langs[cls].append((code, arg))
    indic_codes = sorted({arg for _, arg in langs["IndicNLPTokenizer"]})
    assert all(arg == "" for _, arg in langs["WhitespaceTokenizer"])
    rows = []
    for code in indic_codes:
        if code == "ur":
            rows.append(f'    ("{code}", Script::Urdu, false),\n')
            continue
        base = langinfo.SCRIPT_RANGES[code][0]
        script = "Script::Sinhala" if code == "si" else f"Script::Offset(0x{base:x})"
        rows.append(f'    ("{code}", {script}, {str(langinfo.is_danda_delim(code)).lower()}),\n')
    out.append(
        "\n/// indic-nlp language codes datatrove uses: (code, script for\n"
        "/// `UnicodeIndicTransliterator.transliterate(text, code, 'hi')`,\n"
        "/// `langinfo.is_danda_delim(code)`), sorted by code.\n"
        f"pub(super) static LANGS: [(&str, Script, bool); {len(rows)}] = [\n"
        + "".join(rows)
        + "];\n"
    )
    body = "".join(f'    ("{c}", "{a}"),\n' for c, a in langs["IndicNLPTokenizer"])
    out.append(
        "/// datatrove language codes whose tokenizer is `IndicNLPTokenizer(code)`, sorted.\n"
        f"pub(super) static INDIC_LANGUAGES: &[(&str, &str)] = &[\n{body}];\n"
    )
    body = "".join(f'    "{c}",\n' for c, _ in langs["WhitespaceTokenizer"])
    out.append(
        "/// datatrove language codes whose tokenizer is `WhitespaceTokenizer()`, sorted.\n"
        f"pub(crate) static WHITESPACE_LANGUAGES: &[&str] = &[\n{body}];\n"
    )

    # ---- urduhack
    eos = _load_eos(eos_path)
    out.append("\n// ---- urduhack 1.0.3 `tokenization/eos.py` ----\n\n")
    for name in ("_URDU_CONJUNCTIONS", "_URDU_NEWLINE_WORDS"):
        words = sorted(set(getattr(eos, name)), key=lambda s: s.encode())
        body = ", ".join(_rs_str(w) for w in words)
        out.append(f"/// `{name}`, sorted by UTF-8 bytes.\n")
        out.append(f"pub(super) static {name.strip('_')}: &[&str] = &[{body}];\n")

    # ---- WhitespaceTokenizer
    ws = dwt.WhitespaceTokenizer()
    term = rf"[{re.escape(''.join(TERMINAL_PUNCTUATION))}\n]"
    want = rf"(?:(?:\p{{Lu}}\.)|.)+?{term}+[\"'”]?"
    assert ws._sent_regex.pattern == want, "WhitespaceTokenizer's pattern changed"
    assert ws._sent_regex.flags & regex.UNICODE
    dot = _class(regex.compile("."))
    assert len(dot) == MAX_CP - 0x800 - 1, "`.` must exclude only \\n"
    assert 0x0A not in dot
    lu = _class(regex.compile(r"\p{Lu}"))
    terminal = _class(regex.compile(term))
    quote = _class(regex.compile("[\"'”]"))
    assert quote == [0x22, 0x27, 0x201D]
    assert not set(quote) & set(terminal)
    assert not set(lu) & set(terminal)
    assert 0x2E in terminal
    out.append(f"\n// ---- datatrove `WhitespaceTokenizer` (regex {regex.__version__}) ----\n\n")
    out.append(
        _emit_ranges("LU", f"`regex` {regex.__version__}'s `\\p{{Lu}}`.", _ranges(lu), "pub(crate)")
    )
    out.append(
        _emit_chars(
            "WS_TERMINAL",
            "The pattern's terminal class (`TERMINAL_PUNCTUATION` and `\\n`).",
            terminal,
            "pub(crate)",
        )
    )

    (HERE / "indic_tables.rs").write_text("".join(out))
    print("versions:", ", ".join(f"{d['unicode']}={d['python']}" for d in dumps))
    print(
        f"numeric tables: {len(groups)}; "
        f"indic punct {len(indic_punct)}, urdu punct {len(urdu_punct)}"
    )
    print(
        f"delims: danda {len(danda)}, no danda {len(no_danda)}; "
        f"{len(ack)} acronyms; {len(sinh)} sinhala"
    )
    print(
        f"indic codes {indic_codes}; {len(langs['IndicNLPTokenizer'])} indic / "
        f"{len(langs['WhitespaceTokenizer'])} whitespace datatrove languages"
    )
    print(f"Lu {len(lu)} chars (regex {regex.__version__}); terminal {len(terminal)}")


if __name__ == "__main__":
    if len(sys.argv) >= 3 and sys.argv[1] == "dump":
        dump(sys.argv[2])
    elif len(sys.argv) >= 5 and sys.argv[1] == "emit" and sys.argv[2] == "--eos":
        emit(sys.argv[3], sys.argv[4:])
    else:
        raise SystemExit(__doc__)
