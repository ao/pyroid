"""Generate `unicode_tables.rs`, the tables behind `pyroid_core::filters::unicode`.

The tables are dumped from CPython's own `str`, `re` and `unicodedata`, one
interpreter per Unicode version, by testing every code point:

* `alpha`: `chr(c).isalpha()`
* `punct`: `unicodedata.category(chr(c)).startswith("P")`
* `word`:  `re.match(r"\\w", chr(c)) is not None` (str pattern, default flags)
* `digit`: `re.match(r"\\d", chr(c)) is not None`
* `space`: `chr(c).isspace()`

Surrogates (U+D800..U+DFFF) are never recorded: a Rust `char` cannot be one.

`emit` checks the cross-version invariants the Rust side relies on (`space` is
the same everywhere, and so is every property on ASCII; lowercasing only
produces ASCII from A-Z, U+0130 and U+212A), then writes, per property, an
ASCII mask plus one range table per distinct version (equal tables are shared).

Usage (Linux or a Linux container; `/target/venv-$v` stands for a venv per CPython version):

    # 1. dump one JSON file per interpreter (one per Unicode version)
    for v in 311 312 313 314 315; do
        /target/venv-$v/bin/python generate_unicode_tables.py dump /target/gen-filters/$v.json
    done
    # 2. check the invariants, then write unicode_tables.rs next to this script
    /target/venv-315/bin/python generate_unicode_tables.py emit /target/gen-filters/*.json
"""

# ruff: noqa: T201  (a build script: it reports what it wrote on stdout)

from __future__ import annotations

import json
import re
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = (
    "// @generated by generate_unicode_tables.py -- do not edit by hand.\n"
    "// Dumped from CPython's `str`, `re` and `unicodedata` behaviour, per Unicode version.\n"
)
MAX_CP = 0x110000

# unicodedata.unidata_version -> `crate::ftfy::UnicodeVersion` variant.
VERSIONS = {
    "14.0.0": "V14_0",
    "15.0.0": "V15_0",
    "15.1.0": "V15_1",
    "16.0.0": "V16_0",
    "17.0.0": "V17_0",
}
# Properties that get a table per Unicode version, with their Rust doc text.
PER_VERSION = {
    "alpha": "`str.isalpha()`",
    "punct": '`unicodedata.category(c).startswith("P")`',
    "word": "`re`'s `\\w` (str pattern, default flags)",
    "digit": "`re`'s `\\d` (str pattern, default flags)",
}
# Characters whose `lower()` is different and contains an ASCII character.
LOWER_ASCII = [*range(0x41, 0x5B), 0x130, 0x212A]


# --------------------------------------------------------------------------
# dump: run under one interpreter
# --------------------------------------------------------------------------


def _chars():
    """Every code point except the surrogates, as a 1-character str."""
    for cp in range(MAX_CP):
        if not 0xD800 <= cp < 0xE000:
            yield cp, chr(cp)


def _ranges(hits: set[int]) -> list[list[int]]:
    """Sorted, merged inclusive ranges covering exactly `hits`."""
    out: list[list[int]] = []
    for cp in sorted(hits):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def dump(path: str) -> None:
    word, digit = re.compile(r"\w"), re.compile(r"\d")
    preds = {
        "alpha": str.isalpha,
        "punct": lambda ch: unicodedata.category(ch).startswith("P"),
        "word": lambda ch: word.match(ch) is not None,
        "digit": lambda ch: digit.match(ch) is not None,
        "space": str.isspace,
    }
    hits: dict[str, set[int]] = {name: set() for name in preds}
    lower_ascii = []
    for cp, ch in _chars():
        for name, pred in preds.items():
            if pred(ch):
                hits[name].add(cp)
        low = ch.lower()
        if low != ch and any(ord(x) < 0x80 for x in low):
            lower_ascii.append(cp)
    data = {
        "python": sys.version.split()[0],
        "unicode": unicodedata.unidata_version,
        "props": {name: _ranges(s) for name, s in hits.items()},
        "lower_ascii": lower_ascii,
    }
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(json.dumps(data, sort_keys=True))
    print(f"wrote {path}: Python {data['python']}, Unicode {data['unicode']}")


# --------------------------------------------------------------------------
# emit: combine the dumps and write Rust
# --------------------------------------------------------------------------


def _ascii_mask(ranges: list[list[int]]) -> int:
    mask = 0
    for a, b in ranges:
        for cp in range(a, min(b, 0x7F) + 1):
            mask |= 1 << cp
    return mask


def _non_ascii(ranges: list[list[int]]) -> list[tuple[int, int]]:
    return [(max(a, 0x80), b) for a, b in ranges if b >= 0x80]


def _emit_ranges(name: str, ranges) -> str:
    body = ", ".join(f"(0x{a:x}, 0x{b:x})" for a, b in ranges)
    return f"pub(super) static {name}: [(u32, u32); {len(ranges)}] = [{body}];\n"


def _short(unicode: str) -> str:
    return unicode.removesuffix(".0")


def emit(paths: list[str]) -> None:
    dumps = [json.loads(Path(p).read_text()) for p in paths]
    dumps.sort(key=lambda d: [int(x) for x in d["unicode"].split(".")])
    got = [d["unicode"] for d in dumps]
    assert got == list(VERSIONS), f"need exactly one dump per version {list(VERSIONS)}, got {got}"

    space = dumps[0]["props"]["space"]
    for d in dumps[1:]:
        assert d["props"]["space"] == space, f"str.isspace differs on Python {d['python']}"
    for d in dumps:
        real = d["lower_ascii"]
        assert real == LOWER_ASCII, (
            f"Python {d['python']}: chars whose lower() adds ASCII are "
            + ", ".join(f"U+{c:04X}" for c in real)
        )

    out = [
        HEADER,
        "//! Per-Unicode-version character properties for `filters::unicode`.\n",
        "//!\n",
        "//! For each property: `<NAME>_ASCII`, bit c set iff ASCII char c has it (the same\n",
        "//! in every version), and sorted, merged inclusive ranges of the code points\n",
        "//! >= U+0080 that have it, one static per distinct table.\n\n",
        "#![allow(clippy::unreadable_literal)]\n\n",
        "use crate::ftfy::UnicodeVersion;\n",
    ]
    sizes = []
    for prop, doc in PER_VERSION.items():
        name = prop.upper()
        masks = {_ascii_mask(d["props"][prop]) for d in dumps}
        assert len(masks) == 1, f"{prop} differs between versions on ASCII"
        (mask,) = masks
        # One static per distinct table, named after the oldest version using it.
        groups: dict[tuple, list[dict]] = {}
        for d in dumps:
            groups.setdefault(tuple(_non_ascii(d["props"][prop])), []).append(d)
        out.append(f"\n// ---- {prop}: {doc} ----\n\n")
        out.append(f"/// {doc} for ASCII: bit c is set iff `char::from(c)` has it.\n")
        out.append(f"pub(super) const {name}_ASCII: u128 = 0x{mask:032x};\n")
        arms = []
        for table, ds in groups.items():
            tag = _short(ds[0]["unicode"]).replace(".", "_")
            used = ", ".join(f"Unicode {_short(d['unicode'])} (CPython {d['python']})" for d in ds)
            out.append(f"/// {doc} for code points >= U+0080: {used}.\n")
            out.append(_emit_ranges(f"{name}_{tag}", table))
            pats = " | ".join(f"UnicodeVersion::{VERSIONS[d['unicode']]}" for d in ds)
            arms.append(f"        {pats} => &{name}_{tag},\n")
            sizes.append((prop, [_short(d["unicode"]) for d in ds], len(table)))
        out.append(f"\n/// The `{name}_*` table for Unicode version `v`.\n")
        out.append("#[inline]\n")
        out.append(f"pub(super) fn {prop}(v: UnicodeVersion) -> &'static [(u32, u32)] {{\n")
        out.append("    match v {\n" + "".join(arms) + "    }\n}\n")
    out.append("\n// ---- space: `str.isspace()` (the same in every supported version) ----\n\n")
    out.append("/// `str.isspace()`, all code points; the tests check `is_space` against it.\n")
    out.append("#[cfg(test)]\n")
    out.append(_emit_ranges("SPACE", [tuple(r) for r in space]))
    (HERE / "unicode_tables.rs").write_text("".join(out))

    total = 0
    for prop, vs, n in sizes:
        total += 8 * n
        print(f"{prop:5} {'/'.join(vs):24} {n:4} ranges")
    total += 16 * len(PER_VERSION)
    print(f"wrote unicode_tables.rs: ~{total} bytes of tables (+{8 * len(space)} test-only)")
    print("versions:", ", ".join(f"{d['unicode']}={d['python']}" for d in dumps))
    print(f"str.isspace identical in all versions: {len(space)} ranges")
    print("lower() adds ASCII only for A-Z, U+0130, U+212A in all versions")


if __name__ == "__main__":
    if len(sys.argv) >= 3 and sys.argv[1] == "dump":
        dump(sys.argv[2])
    elif len(sys.argv) >= 3 and sys.argv[1] == "emit":
        emit(sys.argv[2:])
    else:
        raise SystemExit(__doc__)
