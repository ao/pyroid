"""Write tables.rs: the non-ASCII code points `str.isprintable()` accepts, per CPython version.

Run in the dev container with CPython 3.11 to 3.15, oldest first (each interpreter dumps its own
unicodedata):
    P=/opt/python; $P/cpython-3.13-linux-aarch64-gnu/bin/python3.13 -I generate_tables.py \
        /target/uv-python/cpython-3.11.18-linux-aarch64-gnu/bin/python3.11 \
        $P/cpython-3.1[2345]-linux-aarch64-gnu/bin/python3.1[2345] > tables.rs
The sets only grow from one version to the next (checked), so the table is the union of
ranges, each tagged with the first version that has it.
"""

import json
import subprocess
import sys

DUMP = r"""
import json, sys, unicodedata
out, start = [], None
for cp in range(0x80, 0x110001):
    p = cp < 0x110000 and chr(cp).isprintable()
    if p and start is None:
        start = cp
    elif not p and start is not None:
        out.append((start, cp - 1))
        start = None
json.dump({"unicode": unicodedata.unidata_version, "ranges": out}, sys.stdout)
"""


def expand(ranges):
    s = set()
    for lo, hi in ranges:
        s.update(range(lo, hi + 1))
    return s


def main():
    dumps = [json.loads(subprocess.check_output([py, "-I", "-c", DUMP])) for py in sys.argv[1:]]
    sets = [expand(d["ranges"]) for d in dumps]
    for a, b in zip(sets, sets[1:]):
        assert a <= b, "a later version drops printable code points"
    first = {}
    for i, s in enumerate(sets):
        for cp in s:
            first.setdefault(cp, i)
    rows, cps = [], sorted(first)
    i = 0
    while i < len(cps):
        j = i
        while j + 1 < len(cps) and cps[j + 1] == cps[j] + 1 and first[cps[j + 1]] == first[cps[i]]:
            j += 1
        rows.append((cps[i], cps[j], first[cps[i]]))
        i = j + 1
    versions = ", ".join(d["unicode"] for d in dumps)
    print("// Generated by generate_tables.py from CPython's unicodedata; do not edit.")
    print(f"//! `str.isprintable()` above U+007F for Unicode {versions}.")
    print()
    print("/// Sorted, disjoint `(first, last, version index)` ranges of printable code points;")
    print("/// version index 0 is the oldest version listed in the header.")
    print(f"pub(super) static PRINTABLE: [(u32, u32, u8); {len(rows)}] = [")
    for lo, hi, v in rows:
        print(f"    (0x{lo:X}, 0x{hi:X}, {v}),")
    print("];")


main()
