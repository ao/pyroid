# ruff: noqa: T201  (a build script: it reports what it wrote on stdout)
"""Generate `unicode_tables.rs`: the `str` predicates pyvi's CRF features use, per Unicode version.

pyvi's `word2features` reads `word.isupper()`, `word.istitle()` and `word.isdigit()`, and
spaCy's merge rule reads `word[0].isdigit()` and `word[0].istitle()`. CPython answers them
from three per-character flags and one digit property of its Unicode database:

* `upper`: `Py_UNICODE_ISUPPER`, dumped as `chr(c).isupper()`;
* `lower`: `Py_UNICODE_ISLOWER`, dumped as `chr(c).islower()`;
* `title`: `Py_UNICODE_ISTITLE` (general category Lt), dumped as `category(c) == "Lt"`;
* `digit`: `Py_UNICODE_ISDIGIT`, dumped as `chr(c).isdigit()`.

`dump` checks that `chr(c).istitle()` is `upper or title` for every code point (CPython's
one-character shortcut), and that no code point is both `upper` and `title`, so the
multi-character loops in `str.isupper`/`str.istitle` can be rebuilt from these tables.
Surrogates are left out (a Rust `char` cannot be one).

Usage (in the pyroid-dev container, never on the host):

    for v in 3.11 3.12 3.13 3.14 3.15; do
        uv run --no-project -p $v python -I generate_unicode.py dump /target/gen-pyvi/$v.json
    done
    uv run --no-project -p 3.15 python -I generate_unicode.py emit /target/gen-pyvi/*.json
"""

from __future__ import annotations

import json
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = (
    "// @generated by generate_unicode.py -- do not edit by hand.\n"
    "// Dumped from CPython's `str` and `unicodedata`, per Unicode version.\n"
)
MAX_CP = 0x110000
VERSIONS = {
    "14.0.0": "V14_0",
    "15.0.0": "V15_0",
    "15.1.0": "V15_1",
    "16.0.0": "V16_0",
    "17.0.0": "V17_0",
}
PROPS = {
    "upper": "`chr(c).isupper()` (`Py_UNICODE_ISUPPER`)",
    "lower": "`chr(c).islower()` (`Py_UNICODE_ISLOWER`)",
    "title": '`unicodedata.category(c) == "Lt"` (`Py_UNICODE_ISTITLE`)',
    "digit": "`chr(c).isdigit()` (`Py_UNICODE_ISDIGIT`)",
}


def _ranges(hits: list[int]) -> list[list[int]]:
    out: list[list[int]] = []
    for cp in hits:
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def dump(path: str) -> None:
    hits: dict[str, list[int]] = {name: [] for name in PROPS}
    for cp in range(MAX_CP):
        if 0xD800 <= cp < 0xE000:
            continue
        ch = chr(cp)
        upper, lower = ch.isupper(), ch.islower()
        title = unicodedata.category(ch) == "Lt"
        assert ch.istitle() == (upper or title), hex(cp)
        assert not (upper and title), hex(cp)
        for name, value in (("upper", upper), ("lower", lower), ("title", title), ("digit", ch.isdigit())):
            if value:
                hits[name].append(cp)
    data = {
        "python": sys.version.split()[0],
        "unicode": unicodedata.unidata_version,
        "props": {name: _ranges(h) for name, h in hits.items()},
    }
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(json.dumps(data, sort_keys=True))
    print(f"wrote {path}: Python {data['python']}, Unicode {data['unicode']}")


def _mask(ranges: list[list[int]]) -> int:
    m = 0
    for lo, hi in ranges:
        for cp in range(lo, min(hi, 0x7F) + 1):
            m |= 1 << cp
    return m


def _non_ascii(ranges: list[list[int]]) -> list[tuple[int, int]]:
    return [(max(lo, 0x80), hi) for lo, hi in ranges if hi >= 0x80]


def emit(paths: list[str]) -> None:
    dumps = sorted((json.loads(Path(p).read_text()) for p in paths), key=lambda d: d["unicode"])
    got = [d["unicode"] for d in dumps]
    assert got == list(VERSIONS), f"need exactly one dump per version {list(VERSIONS)}, got {got}"
    out = [HEADER, "\nuse crate::ftfy::UnicodeVersion;\n"]
    for prop, doc in PROPS.items():
        masks = {_mask(d["props"][prop]) for d in dumps}
        assert len(masks) == 1, f"{prop} differs between versions on ASCII"
        out.append(f"\n// ---- {prop}: {doc} ----\n\n")
        out.append(f"pub(super) const {prop.upper()}_ASCII: u128 = {masks.pop():#x};\n")
        tables: list[tuple[list[tuple[int, int]], list[dict]]] = []
        for d in dumps:
            t = _non_ascii(d["props"][prop])
            for known, ds in tables:
                if known == t:
                    ds.append(d)
                    break
            else:
                tables.append((t, [d]))
        arms = []
        for t, ds in tables:
            name = f"{prop.upper()}_{VERSIONS[ds[0]['unicode']]}"
            used = ", ".join(f"Unicode {d['unicode']} (CPython {d['python']})" for d in ds)
            out.append(f"\n/// {used}.\nstatic {name}: &[(u32, u32)] = &[\n")
            for lo, hi in t:
                out.append(f"    ({lo:#x}, {hi:#x}),\n")
            out.append("];\n")
            pats = " | ".join(f"UnicodeVersion::{VERSIONS[d['unicode']]}" for d in ds)
            arms.append(f"        {pats} => {name},\n")
        out.append(f"\n/// The `{prop}` table for Unicode version `v` (code points from U+0080).\n")
        out.append(f"pub(super) fn {prop}(v: UnicodeVersion) -> &'static [(u32, u32)] {{\n    match v {{\n")
        out.extend(arms)
        out.append("    }\n}\n")
    dest = HERE / "unicode_tables.rs"
    dest.write_text("".join(out))
    print(f"wrote {dest}")


if __name__ == "__main__":
    if len(sys.argv) >= 3 and sys.argv[1] == "dump":
        dump(sys.argv[2])
    elif len(sys.argv) >= 3 and sys.argv[1] == "emit":
        emit(sys.argv[2:])
    else:
        sys.exit(__doc__)
