# Derived from NeMo Curator 1.4.0 (Apache-2.0), © NVIDIA CORPORATION; modified.
"""Generate ``tables.rs``: the code points NeMo Curator's ``regex_alpha`` matches.

NeMo's ``WordsWithoutAlphabetsFilter`` tests each word with ``regex.compile("[[:alpha:]]")``
from the third-party ``regex`` module. That class is ``regex``'s own Alphabetic property at the
Unicode version ``regex`` ships, which is not what ``str.isalpha()`` or this interpreter's
``unicodedata`` say. So the table is read from ``regex`` itself, code point by code point.

Run in the dev container, with the ``regex`` release to record (the test pin, 2026.9.29) in the
venv, from the repository root::

    python crates/pyroid-core/src/nemo/generate_tables.py
    rustfmt --edition 2024 crates/pyroid-core/src/nemo/tables.rs

``--out PATH`` writes elsewhere (to compare two ``regex`` releases). The script also checks that
NeMo's ``regex_digit`` (``[[:digit:]]``) is ASCII 0-9, which the kernel assumes.
"""

from __future__ import annotations

import argparse
import importlib.metadata
import re
import sys
from pathlib import Path

import regex

OUT = Path(__file__).with_name("tables.rs")
MAX_CP = 0x110000
SURROGATES = range(0xD800, 0xE000)


def regex_unicode_version() -> str:
    """The Unicode version the installed ``regex`` release documents in its metadata."""
    meta = importlib.metadata.metadata("regex").get_payload()  # type: ignore[attr-defined]
    found = re.search(r"supports Unicode (\d+\.\d+\.\d+)", str(meta))
    if not found:
        sys.exit("could not find the Unicode version in regex's metadata")
    return found.group(1)


def runs(flags: list[bool]) -> list[tuple[int, int]]:
    """Maximal runs ``(first, last)`` of code points whose flag is set."""
    out: list[tuple[int, int]] = []
    for cp, on in enumerate(flags):
        if not on:
            continue
        if out and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def main() -> None:
    """Write tables.rs (or ``--out``)."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=OUT)
    out_path: Path = parser.parse_args().out

    regex_version = importlib.metadata.version("regex")
    unicode_version = regex_unicode_version()
    alpha = regex.compile("[[:alpha:]]")
    digit = regex.compile("[[:digit:]]")

    flags = []
    for cp in range(MAX_CP):
        ch = chr(cp)
        is_alpha = alpha.search(ch) is not None
        # pyroid never sees a lone surrogate (a str holding one has no UTF-8 form).
        flags.append(is_alpha and cp not in SURROGATES)
        if (digit.search(ch) is not None) != (0x30 <= cp <= 0x39):
            sys.exit(f"[[:digit:]] is not ASCII 0-9 in regex {regex_version}: U+{cp:04X}")
    ascii_alpha = [cp for cp in range(0x80) if flags[cp]]
    if ascii_alpha != [*range(0x41, 0x5B), *range(0x61, 0x7B)]:
        sys.exit("[[:alpha:]] is not A-Z, a-z in ASCII")

    table = runs(flags)
    lines = [
        "// Derived from NeMo Curator 1.4.0 (Apache-2.0), © NVIDIA CORPORATION; modified.",
        f"// @generated by generate_tables.py from regex {regex_version}; do not edit.",
        '//! NeMo\'s `regex_alpha` (`regex.compile("[[:alpha:]]")`) as code point runs '
        "(generated).",
        "",
        "/// The `regex` release the table was read from.",
        f'pub const REGEX_VERSION: &str = "{regex_version}";',
        "/// The Unicode version of that `regex` release (from its metadata).",
        f'pub const REGEX_UNICODE_VERSION: &str = "{unicode_version}";',
        "",
        "/// `(first, last)` runs of the code points `[[:alpha:]]` matches, sorted and disjoint.",
        "pub static ALPHA: &[(u32, u32)] = &[",
    ]
    lines += [f"    (0x{a:04X}, 0x{b:04X})," for a, b in table]
    lines += ["];", ""]
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out_path}: {len(table)} runs, {sum(flags)} code points")  # noqa: T201


if __name__ == "__main__":
    main()
