"""Generate the static tables behind `pyroid_core::ftfy`.

Derived from ftfy 6.3.1 (Apache-2.0), © Robyn Speer; modified.

Every table is extracted from the running ftfy 6.3.1 and CPython rather than
transcribed by hand:

* the character classes of `BADNESS_RE` and `UTF8_DETECTOR_RE` come from
  CPython's own regex parser (`re._parser`), so they are exactly what `re`
  matches;
* the single-byte codecs, HTML entities, width map and ligatures come from the
  same objects ftfy builds at import time;
* `\\s`, `\\w`, `\\d` and the assigned-code-point sets are dumped per Unicode
  version by testing every code point with that interpreter's `re`.

Usage (inside the pyroid-dev container; never on the host):

    # 1. dump one JSON file per interpreter (one per Unicode version)
    for v in 311 312 313 314 315; do
        /target/venv-$v/bin/python generate_tables.py dump /target/gen/$v.json
    done
    # 2. check the version-independent parts agree, then write the Rust files
    python generate_tables.py emit /target/gen/*.json
"""

# ruff: noqa: PT018  (a build script, not a test)

from __future__ import annotations

import json
import re
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = (
    "// @generated by generate_tables.py -- do not edit by hand.\n"
    "// Derived from ftfy 6.3.1 (Apache-2.0), © Robyn Speer; modified.\n"
)
MAX_CP = 0x110000


# --------------------------------------------------------------------------
# dump: run under one interpreter
# --------------------------------------------------------------------------


def _ranges(pred) -> list[list[int]]:
    """Inclusive code point ranges where `pred(cp)` holds."""
    out: list[list[int]] = []
    start = None
    for cp in range(MAX_CP + 1):
        hit = cp < MAX_CP and pred(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append([start, cp - 1])
            start = None
    return out


def _class_items_to_set(items, sre_constants) -> tuple[set[int], bool]:
    """Turn the items of an sre IN node into (explicit set, negated)."""
    chars: set[int] = set()
    negate = False
    for op, arg in items:
        if op is sre_constants.NEGATE:
            negate = True
        elif op is sre_constants.LITERAL:
            chars.add(arg)
        elif op is sre_constants.RANGE:
            chars.update(range(arg[0], arg[1] + 1))
        else:
            raise ValueError(f"unsupported class item {op} {arg}")
    return chars, negate


def _element(op, arg, sre_constants) -> dict:
    """One fixed-width element of an alternative."""
    if op is sre_constants.LITERAL:
        return {"kind": "set", "chars": [arg]}
    if op is sre_constants.ANY:
        return {"kind": "any"}
    if op is sre_constants.IN:
        if len(arg) == 1 and arg[0][0] is sre_constants.CATEGORY:
            cat = str(arg[0][1])
            if cat == "CATEGORY_SPACE":
                return {"kind": "space"}
            if cat == "CATEGORY_WORD":
                return {"kind": "word"}
            raise ValueError(cat)
        chars, negate = _class_items_to_set(arg, sre_constants)
        return {"kind": "notset" if negate else "set", "chars": sorted(chars)}
    raise ValueError(f"unsupported element {op} {arg}")


def _badness_alternatives() -> list[dict]:
    import re._constants as sre_constants
    import re._parser as sre_parse

    from ftfy.badness import BADNESS_RE

    tree = sre_parse.parse(BADNESS_RE.pattern, re.VERBOSE)
    assert len(tree.data) == 1 and tree.data[0][0] is sre_constants.BRANCH
    alts = []
    for branch in tree.data[0][1][1]:
        anchored = False
        variants: list[list[dict]] = [[]]
        for op, arg in branch.data:
            if op is sre_constants.AT:
                assert str(arg) == "AT_BEGINNING" and not any(variants[0])
                anchored = True
            elif op is sre_constants.MAX_REPEAT:
                lo, hi, sub = arg
                assert (lo, hi) == (0, 1) and len(sub.data) == 1
                el = _element(*sub.data[0], sre_constants)
                # expand greedy `x?` into "with x", then "without x" (sre's order)
                variants = [v for base in variants for v in ([*base, el], list(base))]
            else:
                el = _element(op, arg, sre_constants)
                variants = [[*v, el] for v in variants]
        alts.extend({"anchored": anchored, "elements": v} for v in variants)
    return alts


def _utf8_detector() -> dict:
    import re._constants as sre_constants
    import re._parser as sre_parse

    from ftfy.chardata import UTF8_DETECTOR_RE

    tree = sre_parse.parse(UTF8_DETECTOR_RE.pattern, re.VERBOSE)
    (op0, behind), (op1, rep) = tree.data
    assert str(op0) == "ASSERT_NOT" and behind[0] == -1
    ((bop, barg),) = behind[1].data
    strict, neg = _class_items_to_set(barg, sre_constants)
    assert bop is sre_constants.IN and not neg
    lo, _hi, sub = rep
    assert str(op1) == "MAX_REPEAT" and lo == 1
    ((gop, garg),) = sub.data
    assert str(gop) == "SUBPATTERN"
    ((brop, brarg),) = garg[3].data
    assert brop is sre_constants.BRANCH
    seqs = []
    for branch in brarg[1]:
        first_op, first_arg = branch.data[0]
        first, neg = _class_items_to_set(first_arg, sre_constants)
        assert first_op is sre_constants.IN and not neg
        if len(branch.data) == 2 and branch.data[1][0] is sre_constants.IN:
            cont, neg = _class_items_to_set(branch.data[1][1], sre_constants)
            count = 1
        else:
            ((rop, (rlo, rhi, rsub)),) = branch.data[1:]
            assert str(rop) == "MAX_REPEAT" and rlo == rhi
            ((_cop, carg),) = rsub.data
            cont, neg = _class_items_to_set(carg, sre_constants)
            count = rlo
        assert not neg
        seqs.append({"first": sorted(first), "cont": sorted(cont), "count": count})
    assert [s["count"] for s in seqs] == [1, 2, 3]
    assert seqs[0]["cont"] == seqs[1]["cont"] == seqs[2]["cont"]
    return {
        "strict": sorted(strict),
        "first2": seqs[0]["first"],
        "first3": seqs[1]["first"],
        "first4": seqs[2]["first"],
        "cont": seqs[0]["cont"],
    }


def _charmaps() -> dict:
    import ftfy.bad_codecs  # noqa: F401  (registers sloppy-* and utf-8-variants)
    from ftfy.chardata import CHARMAP_ENCODINGS, ENCODING_REGEXES

    out = {}
    for enc in [*CHARMAP_ENCODINGS, "windows-1252"]:
        table = []
        for b in range(256):
            try:
                ch = bytes([b]).decode(enc)
                assert len(ch) == 1
                table.append(ord(ch))
            except UnicodeDecodeError:
                table.append(-1)
        if enc != "windows-1252":
            # possible_encoding(text, enc) must be "every char is in the table"
            image = {c for c in table if c >= 0}
            for cp in range(0x3000):
                ch = chr(cp)
                assert bool(ENCODING_REGEXES[enc].match(ch)) == (cp in image), (enc, cp)
                if cp in image:
                    assert ch.encode(enc) == bytes([table.index(cp)]), (enc, cp)
        out[enc] = table
    return {"order": list(CHARMAP_ENCODINGS), "tables": out}


def _html_entities() -> list[list[str]]:
    from ftfy.chardata import HTML_ENTITIES

    return sorted([k, v] for k, v in HTML_ENTITIES.items())


def _numeric_charref_rules() -> dict:
    """The tables html.unescape uses for numeric character references."""
    from html import _invalid_charrefs, _invalid_codepoints  # type: ignore[attr-defined]

    return {
        "invalid_charrefs": sorted([k, ord(v)] for k, v in _invalid_charrefs.items()),
        "invalid_codepoints": sorted(_invalid_codepoints),
    }


def _width_and_ligatures() -> dict:
    from ftfy.chardata import CONTROL_CHARS, LIGATURES, WIDTH_MAP

    return {
        "width": sorted([k, v] for k, v in WIDTH_MAP.items()),
        "ligatures": sorted([k, v] for k, v in LIGATURES.items()),
        "control": sorted(CONTROL_CHARS),
    }


def _sloppy_1252() -> list[int]:
    import ftfy.bad_codecs  # noqa: F401

    return [ord(bytes([b]).decode("sloppy-windows-1252")) for b in range(0x80, 0xA0)]


def _unicode_props() -> dict:
    sp, wd, dg = re.compile(r"\s"), re.compile(r"\w"), re.compile(r"\d")

    def assigned(cp: int) -> bool:
        return unicodedata.category(chr(cp)) != "Cn"

    return {
        "space": _ranges(lambda cp: sp.match(chr(cp)) is not None),
        "word": _ranges(lambda cp: wd.match(chr(cp)) is not None),
        "digit": _ranges(lambda cp: dg.match(chr(cp)) is not None),
        "assigned": _ranges(assigned),
        "nfc_active": _ranges(_nfc_active_set().__contains__),
    }


def _nfc_active_set() -> set[int]:
    """Code points that can make NFC change a string they appear in.

    A character is NFC-inert if it has combining class 0, is NFC on its own
    (Quick_Check != No) and is never the second character of a canonical
    composition (Quick_Check != Maybe). A string of inert characters is NFC.
    """
    active: set[int] = set()
    for cp in range(MAX_CP):
        if 0xD800 <= cp < 0xE000:
            continue
        ch = chr(cp)
        if unicodedata.combining(ch) or not unicodedata.is_normalized("NFC", ch):
            active.add(cp)
        d = unicodedata.decomposition(ch)
        if d and not d.startswith("<"):
            parts = [int(x, 16) for x in d.split()]
            if (
                len(parts) == 2
                and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == ch
            ):
                active.add(parts[1])
    active.update(range(0x1161, 0x1176))  # Hangul V jamo compose with L
    active.update(range(0x11A8, 0x11C3))  # Hangul T jamo compose with LV
    return active


def dump(path: str) -> None:
    import ftfy

    assert ftfy.__version__ == "6.3.1", ftfy.__version__
    data = {
        "python": sys.version.split()[0],
        "unicode": unicodedata.unidata_version,
        "independent": {
            "badness": _badness_alternatives(),
            "utf8_detector": _utf8_detector(),
            "charmaps": _charmaps(),
            "html_entities": _html_entities(),
            "charrefs": _numeric_charref_rules(),
            "maps": _width_and_ligatures(),
            "sloppy_1252_c1": _sloppy_1252(),
        },
        "props": _unicode_props(),
    }
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(json.dumps(data))
    print(f"wrote {path}: Python {data['python']}, Unicode {data['unicode']}")


