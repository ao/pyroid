def _rs_str(s: str) -> str:
    out = []
    for ch in s:
        cp = ord(ch)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 0x20 <= cp < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\u{{{cp:x}}}")
    return '"' + "".join(out) + '"'


def _emit_ranges(name: str, ranges: list[list[int]]) -> str:
    body = ", ".join(f"(0x{a:x}, 0x{b:x})" for a, b in ranges)
    return f"pub(super) static {name}: [(u32, u32); {len(ranges)}] = [{body}];\n"


def _badness_rust(alts: list[dict]) -> tuple[str, dict[int, int]]:
    """Lay the alternatives out as Shift-And positions in one u128."""
    explicit: dict[int, int] = {}
    masks = {"start": 0, "anchored": 0, "final": 0, "any": 0, "notalpha": 0, "space": 0, "word": 0}
    ascii_alpha = set(range(0x41, 0x5B)) | set(range(0x61, 0x7B))
    pos = 0
    spans = []
    for alt in alts:
        els = alt["elements"]
        spans.append((pos, len(els), alt["anchored"]))
        masks["anchored" if alt["anchored"] else "start"] |= 1 << pos
        for el in els:
            bit = 1 << pos
            kind = el["kind"]
            if kind == "set":
                for c in el["chars"]:
                    explicit[c] = explicit.get(c, 0) | bit
            elif kind == "notset":
                assert set(el["chars"]) == ascii_alpha, "only [^A-Za-z] is supported"
                masks["notalpha"] |= bit
            else:
                masks[kind] |= bit
            pos += 1
        masks["final"] |= 1 << (pos - 1)
    assert pos <= 128, pos
    lines = [f"/// Shift-And layout of `BADNESS_RE`: {len(alts)} alternatives, {pos} positions.\n"]
    for k, v in masks.items():
        lines.append(f"pub(super) const BAD_{k.upper()}: u128 = 0x{v:x};\n")
    lines.append(
        "/// Each alternative in `BADNESS_RE` order: (first bit, length, anchored at `^`).\n"
    )
    body = ", ".join(f"({a}, {b}, {str(c).lower()})" for a, b, c in spans)
    lines.append(f"pub(super) static BAD_ALTS: [(u8, u8, bool); {len(spans)}] = [{body}];\n")
    return "".join(lines), explicit


def emit(paths: list[str]) -> None:
    dumps = [json.loads(Path(p).read_text()) for p in paths]
    dumps.sort(key=lambda d: [int(x) for x in d["unicode"].split(".")])
    base = dumps[0]["independent"]
    for d in dumps[1:]:
        for key, val in d["independent"].items():
            assert val == base[key], f"{key} differs on Python {d['python']}"
    space = dumps[0]["props"]["space"]
    for d in dumps[1:]:
        assert d["props"]["space"] == space, f"\\s differs on Python {d['python']}"

    # ---- version-independent tables --------------------------------------
    alts = base["badness"]
    bad_rs, bad_explicit = _badness_rust(alts)
    det = base["utf8_detector"]
    clue_bits = {"first2": 1, "first3": 2, "first4": 4, "cont": 8, "strict": 16}
    clue: dict[int, int] = {}
    for key, bit in clue_bits.items():
        for c in det[key]:
            clue[c] = clue.get(c, 0) | bit
    cm = base["charmaps"]
    order = cm["order"]
    enc: dict[int, int] = {}
    for i, name in enumerate(order):
        for c in cm["tables"][name]:
            if c >= 0:
                enc[c] = enc.get(c, 0) | (1 << i)

    chars = sorted(set(bad_explicit) | set(clue) | set(enc))
    assert max(chars) < 0x10000, "astral chars need a different table layout"
    classes: dict[tuple[int, int, int], int] = {(0, 0, 0): 0}
    cls_of: dict[int, int] = {}
    for c in chars:
        key = (bad_explicit.get(c, 0), clue.get(c, 0), enc.get(c, 0))
        cls_of[c] = classes.setdefault(key, len(classes))
    assert len(classes) <= 256, len(classes)
    pages: list[list[int]] = []
    page_index = [0] * 256
    pages.append([0] * 256)  # page 0 of the list = all-zero page
    for p in range(256):
        row = [cls_of.get((p << 8) | lo, 0) for lo in range(256)]
        if any(row):
            page_index[p] = len(pages)
            pages.append(row)

    out = [HEADER, "//! Static data tables for the ftfy port.\n\n"]
    out.append("#![allow(clippy::unreadable_literal)]\n\n")
    out.append(bad_rs)
    out.append(
        "\n/// Bits of `CharClass::clue` (the `UTF8_DETECTOR_RE` character classes).\n"
        + "".join(f"pub(super) const CLUE_{k.upper()}: u8 = {v};\n" for k, v in clue_bits.items())
    )
    out.append("\n/// `CHARMAP_ENCODINGS`, in ftfy's order; bit i of `CharClass::enc`.\n")
    out.append(f"pub(super) const ENCODING_NAMES: [&str; {len(order)}] = [")
    out.append(", ".join(_rs_str(n) for n in order) + "];\n")
    out.append(
        "\n/// Per-class data: `(badness explicit mask, utf8 clue bits, encodable-in bits)`.\n"
        f"pub(super) static CLASSES: [(u128, u8, u16); {len(classes)}] = [\n"
    )
    for (b, c, e), _ in sorted(classes.items(), key=lambda kv: kv[1]):
        out.append(f"    (0x{b:x}, {c}, 0x{e:x}),\n")
    out.append("];\n")
    out.append("\n/// BMP page -> index into `CLASS_PAGES` (0 = all class 0).\n")
    out.append(f"pub(super) static PAGE_INDEX: [u8; 256] = {page_index};\n")
    out.append(f"pub(super) static CLASS_PAGES: [[u8; 256]; {len(pages)}] = [\n")
    out.extend(f"    {row},\n" for row in pages)
    out.append("];\n")

    out.append("\n/// Decode tables (byte -> code point; u32::MAX = undefined) for\n")
    out.append("/// `ENCODING_NAMES`, followed by strict `windows-1252`.\n")
    names = [*order, "windows-1252"]
    out.append(f"pub(super) static DECODE: [[u32; 256]; {len(names)}] = [\n")
    for name in names:
        row = ", ".join("u32::MAX" if c < 0 else f"0x{c:x}" for c in cm["tables"][name])
        out.append(f"    // {name}\n    [{row}],\n")
    out.append("];\n")
    out.append("\n/// Sorted (code point, byte) pairs for encoding chars >= 0x80, per encoding.\n")
    out.append(f"pub(super) static ENCODE_HIGH: [&[(u32, u8)]; {len(order)}] = [\n")
    for name in order:
        t = cm["tables"][name]
        pairs = sorted((c, b) for b, c in enumerate(t) if c >= 0x80)
        out.append("    &[" + ", ".join(f"(0x{c:x}, 0x{b:x})" for c, b in pairs) + "],\n")
    out.append("];\n")
    out.append("/// Whether the ASCII control byte 0x1A is encodable (non-sloppy codecs only).\n")
    out.append(f"pub(super) const ENCODE_1A: [bool; {len(order)}] = [")
    out.append(", ".join("true" if cm["tables"][n][0x1A] == 0x1A else "false" for n in order))
    out.append("];\n")

    ents = base["html_entities"]
    out.append("\n/// ftfy's `HTML_ENTITIES`, sorted by name.\n")
    out.append(f"pub(super) static HTML_ENTITIES: [(&str, &str); {len(ents)}] = [\n")
    for k, v in ents:
        out.append(f"    ({_rs_str(k)}, {_rs_str(v)}),\n")
    out.append("];\n")
    cr = base["charrefs"]
    out.append("\n/// `html._invalid_charrefs`: numeric reference -> replacement.\n")
    out.append(
        f"pub(super) static INVALID_CHARREFS: [(u32, u32); {len(cr['invalid_charrefs'])}] = ["
    )
    out.append(", ".join(f"(0x{a:x}, 0x{b:x})" for a, b in cr["invalid_charrefs"]) + "];\n")
    out.append("/// `html._invalid_codepoints`: references that decode to nothing.\n")
    out.append(f"pub(super) static INVALID_CODEPOINTS: [u32; {len(cr['invalid_codepoints'])}] = [")
    out.append(", ".join(f"0x{a:x}" for a in cr["invalid_codepoints"]) + "];\n")

    maps = base["maps"]
    out.append("\n/// ftfy's `WIDTH_MAP`.\n")
    out.append(f"pub(super) static WIDTH_MAP: [(u32, &str); {len(maps['width'])}] = [\n")
    for k, v in maps["width"]:
        out.append(f"    (0x{k:x}, {_rs_str(v)}),\n")
    out.append("];\n")
    out.append("/// ftfy's `LIGATURES`.\n")
    out.append(f"pub(super) static LIGATURES: [(u32, &str); {len(maps['ligatures'])}] = [\n")
    for k, v in maps["ligatures"]:
        out.append(f"    (0x{k:x}, {_rs_str(v)}),\n")
    out.append("];\n")
    out.append("/// ftfy's `CONTROL_CHARS` (deleted by `remove_control_chars`).\n")
    out.append(f"pub(super) static CONTROL_CHARS: [u32; {len(maps['control'])}] = [")
    out.append(", ".join(f"0x{c:x}" for c in maps["control"]) + "];\n")
    out.append("/// `sloppy-windows-1252` decoding of bytes 0x80..=0x9F (for `fix_c1_controls`).\n")
    out.append("pub(super) static SLOPPY_1252_C1: [u32; 32] = [")
    out.append(", ".join(f"0x{c:x}" for c in base["sloppy_1252_c1"]) + "];\n")
    # Full Shift-And masks for ASCII (\s and \w agree in every version there).
    sp_ascii = {c for a, b in space for c in range(a, b + 1) if c < 0x80}
    word17 = dumps[-1]["props"]["word"]
    wd_ascii = {c for a, b in word17 for c in range(a, b + 1) if c < 0x80}
    for d in dumps:
        assert {c for a, b in d["props"]["word"] for c in range(a, b + 1) if c < 0x80} == wd_ascii
    bad_masks = dict(re.findall(r"BAD_(\w+): u128 = 0x([0-9a-f]+)", bad_rs))
    m_any, m_notalpha = int(bad_masks["ANY"], 16), int(bad_masks["NOTALPHA"], 16)
    m_space, m_word = int(bad_masks["SPACE"], 16), int(bad_masks["WORD"], 16)
    ascii_masks = []
    for c in range(0x80):
        m = bad_explicit.get(c, 0)
        m |= m_any if c != 0x0A else 0
        m |= 0 if chr(c).isalpha() else m_notalpha
        m |= m_space if c in sp_ascii else 0
        m |= m_word if c in wd_ascii else 0
        ascii_masks.append(m)
    out.append("\n/// Complete Shift-And masks for ASCII characters.\n")
    out.append("pub(super) static BAD_ASCII: [u128; 128] = [")
    out.append(", ".join(f"0x{m:x}" for m in ascii_masks) + "];\n")

    # NFC-active code points (newest version): a BMP bitmap plus astral ranges.
    newest = dumps[-1]["props"]["nfc_active"]
    active = {c for a, b in newest for c in range(a, b + 1)}
    for d in dumps[:-1]:
        older = {c for a, b in d["props"]["nfc_active"] for c in range(a, b + 1)}
        assert older <= active, f"NFC-active set of {d['unicode']} not within newest"
    words = [0] * 1024
    for c in active:
        if c < 0x10000:
            words[c >> 6] |= 1 << (c & 63)
    astral = [[a, b] for a, b in newest if b >= 0x10000]
    astral = [[max(a, 0x10000), b] for a, b in astral]
    out.append("\n/// BMP code points that can make NFC change text (bit set = active).\n")
    out.append("pub(super) static NFC_ACTIVE_BMP: [u64; 1024] = [")
    out.append(", ".join(f"0x{w:x}" for w in words) + "];\n")
    out.append(_emit_ranges("NFC_ACTIVE_ASTRAL", astral))
    (HERE / "tables.rs").write_text("".join(out))

    # ---- per-Unicode-version tables --------------------------------------
    u = [HEADER, "//! Per-Unicode-version character properties, as CPython's `re` sees them.\n\n"]
    u.append("#![allow(clippy::unreadable_literal)]\n\n")
    u.append("/// `\\s` (identical in every supported version).\n")
    u.append(_emit_ranges("SPACE", space))
    for d in dumps:
        tag = d["unicode"].replace(".", "_")
        u.append(f"\n// Unicode {d['unicode']} (CPython {d['python']})\n")
        u.append(_emit_ranges(f"WORD_{tag}", d["props"]["word"]))
        u.append(_emit_ranges(f"DIGIT_{tag}", d["props"]["digit"]))
        u.append(_emit_ranges(f"ASSIGNED_{tag}", d["props"]["assigned"]))
    (HERE / "unicode_tables.rs").write_text("".join(u))
    print(f"wrote tables.rs ({len(classes)} classes, {len(pages)} pages) and unicode_tables.rs")
