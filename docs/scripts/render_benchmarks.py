"""Render the generated tables of docs/benchmarks.md from docs/data/benchmarks.json.

Two blocks, each between its markers:

- ``<!-- bench-chain:begin -->`` / ``<!-- bench-chain:end -->``: the end-to-end FineWeb chain,
  from ``chain`` (``run``, ``wall_s``, ``cpu_s``, ``rss_mib``, ``vs_1_proc``, ``vs_8_procs``);
- ``<!-- bench:begin -->`` / ``<!-- bench:end -->``: one row per stage, from ``rows``
  (``module``, ``call``, ``input``, ``incumbent``, ``incumbent_us``, ``pyroid_us``, ``speedup``,
  ``check``, and optionally ``pyroid_us_8_threads``).

Every value is a string, copied as it is: nothing is computed here. To publish a new consolidated
run, copy ``rows``, ``source`` and (as printed) ``label`` from its ``consolidated.json`` and the
chain table from its ``CONSOLIDATED.md`` into the JSON file (or pass another file with ``--data``)
and rerun.

Usage (stdlib only, any Python 3.11+, from the repository root):

    python docs/scripts/render_benchmarks.py            # rewrite docs/benchmarks.md
    python docs/scripts/render_benchmarks.py --check    # exit 1 if the page is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

DOCS = Path(__file__).resolve().parent.parent
PAGE = DOCS / "benchmarks.md"
DATA = DOCS / "data" / "benchmarks.json"
GUIDE = "guides/{module}.md"
GENERATED = "<!-- Generated by docs/scripts/render_benchmarks.py from docs/data/benchmarks.json. -->"


def render_chain(data: dict[str, Any]) -> list[str]:
    """The end-to-end table: wall time of the whole chain per run."""
    lines = [
        f"*{data['label']}.* Seconds for the whole chain over the same documents, fastest first.",
        "",
        "| Run | Wall s, median [IQR] | CPU s | Peak RSS of one process, MiB "
        "| vs datatrove, 1 process | vs datatrove, 8 processes |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for r in data["chain"]:
        lines.append(
            f"| {r['run']} | {r['wall_s']} | {r['cpu_s']} | {r['rss_mib']} "
            f"| {r['vs_1_proc']} | {r['vs_8_procs']} |"
        )
    return lines


def render_stages(data: dict[str, Any]) -> list[str]:
    """The per-stage table: µs per document, with a pool-of-8 column when the rows have one."""
    threads = any("pyroid_us_8_threads" in r for r in data["rows"])
    head = "| Module | Call | Input | Incumbent | Incumbent µs/doc | pyroid µs/doc, 1 thread "
    rule = "|---|---|---|---|---:|---:|"
    if threads:
        head += "| pyroid µs/doc, 8 threads "
        rule += "---:|"
    lines = [
        f"*{data['label']}.* µs per document. The speedup is pyroid on one thread against the "
        "incumbent in one process.",
        "",
        head + "| Speedup | Output |",
        rule + "---:|---|",
    ]
    for r in data["rows"]:
        module = f"[`pyroid.{r['module']}`]({GUIDE.format(module=r['module'])})"
        cells = [module, r["call"], r["input"], r["incumbent"], r["incumbent_us"], r["pyroid_us"]]
        if threads:
            cells.append(r.get("pyroid_us_8_threads", "—"))
        cells += [f"**{r['speedup']}**", r["check"]]
        lines.append("| " + " | ".join(cells) + " |")
    return lines


BLOCKS: list[tuple[str, Callable[[dict[str, Any]], list[str]]]] = [
    ("bench-chain", render_chain),
    ("bench", render_stages),
]


def render(page: str, data: dict[str, Any]) -> str:
    """The page with every generated block rewritten."""
    for name, body in BLOCKS:
        begin, end = f"<!-- {name}:begin -->", f"<!-- {name}:end -->"
        start, stop = page.index(begin), page.index(end) + len(end)
        lines = [begin, GENERATED, "", *body(data)]
        lines += ["", f"<small>Source: {data['source']}.</small>", end]
        page = page[:start] + "\n".join(lines) + page[stop:]
    return page


def main(argv: list[str] | None = None) -> int:
    """Rewrite (or --check) the generated blocks of docs/benchmarks.md."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data", type=Path, default=DATA)
    parser.add_argument("--check", action="store_true", help="fail if the page is out of date")
    args = parser.parse_args(argv)

    data = json.loads(args.data.read_text(encoding="utf-8"))
    page = PAGE.read_text(encoding="utf-8")
    new = render(page, data)
    if args.check:
        if new != page:
            sys.stderr.write(f"{PAGE} is out of date: run python {Path(__file__).as_posix()}\n")
            return 1
        return 0
    PAGE.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
