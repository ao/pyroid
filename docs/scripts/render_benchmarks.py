"""Render the generated tables of docs/benchmarks.md from docs/data/benchmarks.json.

Each block sits between ``<!-- bench:KIND:KEY:begin -->`` and ``<!-- bench:KIND:KEY:end -->``:

- ``chain``: the end-to-end FineWeb chain of the run ``runs[KEY]`` (its ``chain`` rows: ``run``,
  ``wall_s``, ``cpu_s``, ``rss_mib``, ``vs_1_proc``, ``vs_8_procs``);
- ``stages``: one row per stage of the run ``runs[KEY]`` (its ``rows``: ``module``, ``call``,
  ``input``, ``incumbent``, ``incumbent_us``, ``pyroid_us``, ``speedup``, ``check``, and optionally
  ``pyroid_us_8_threads``), as copied from a ``consolidated.json``;
- ``more``: runs outside the consolidated benchmark (other modules, languages, datatrove steps),
  from ``more``: groups of ``title``, ``guide``, ``note``, ``columns``, ``rows`` (lists of cells),
  optional ``footnote``, and their own ``source``. ``KEY`` is unused (write ``all``).
- ``table``: one hand-entered table, ``tables[KEY]``: ``caption``, ``columns``, ``rows`` (lists of
  cells), optional ``footnote``, and ``source``.

Every value is a string, copied as it is: nothing is computed here. To publish a new consolidated
run, add it under ``runs`` with ``rows`` and ``label`` copied from its ``consolidated.json``, the
chain table from its ``CONSOLIDATED.md``, its folder as ``source`` and a short ``caption``, point
the page's markers at it and rerun.

Usage (stdlib only, any Python 3.11+, from the repository root):

    python docs/scripts/render_benchmarks.py            # rewrite docs/benchmarks.md
    python docs/scripts/render_benchmarks.py --check    # exit 1 if the page is out of date
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

DOCS = Path(__file__).resolve().parent.parent
PAGE = DOCS / "benchmarks.md"
DATA = DOCS / "data" / "benchmarks.json"
GUIDE = "guides/{module}.md"
GENERATED = (
    "<!-- Generated by docs/scripts/render_benchmarks.py from docs/data/benchmarks.json. -->"
)
BEGIN = re.compile(r"<!-- bench:([a-z]+):([\w.-]+):begin -->")


def source(text: str) -> str:
    """The source line under a table."""
    return f"<small>Source: {text}.</small>"


def render_chain(data: dict[str, Any], key: str) -> list[str]:
    """The end-to-end table of one run: wall time of the whole chain, fastest first."""
    run = data["runs"][key]
    lines = [
        f"{run['caption']}. Wall seconds for the whole chain, fastest first.",
        "",
        "| Run | Wall s, median [IQR] | CPU s | Peak RSS of one process, MiB "
        "| vs datatrove, 1 process | vs datatrove, 8 processes |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    lines.extend(
        f"| {r['run']} | {r['wall_s']} | {r['cpu_s']} | {r['rss_mib']} "
        f"| {r['vs_1_proc']} | {r['vs_8_procs']} |"
        for r in run["chain"]
    )
    return [*lines, "", source(run["source"])]


def docs_of(row: dict[str, str]) -> str:
    """The batch size in a row's ``input`` ("FineWeb dev, first 1,000 docs; ..."), or the input."""
    found = re.search(r"first ([\d,]+) docs", row["input"])
    return found[1] if found else row["input"]


def render_stages(data: dict[str, Any], key: str) -> list[str]:
    """The per-stage table of one run: µs per document, with a pool-of-8 column if there is one."""
    run = data["runs"][key]
    rows = run["rows"]
    threads = any("pyroid_us_8_threads" in r for r in rows)
    checks = {r["check"] for r in rows}
    head = "| Module | Call | Docs per call | Incumbent | Incumbent, 1 process | pyroid, 1 thread "
    rule = "|---|---|---:|---|---:|---:|"
    if threads:
        head += "| pyroid, 8 threads "
        rule += "---:|"
    head += "| Speedup |"
    rule += "---:|"
    if len(checks) > 1:
        head += " Output |"
        rule += "---|"
    lines = [
        f"{run['caption']}. µs per document; the speedup is pyroid on one thread against the "
        "incumbent in one process.",
        "",
        head,
        rule,
    ]
    for r in rows:
        module = f"[`pyroid.{r['module']}`]({GUIDE.format(module=r['module'])})"
        cells = [module, r["call"], docs_of(r), r["incumbent"], r["incumbent_us"], r["pyroid_us"]]
        if threads:
            cells.append(r.get("pyroid_us_8_threads", "—"))
        cells.append(r["speedup"])
        if len(checks) > 1:
            cells.append(r["check"])
        lines.append("| " + " | ".join(cells) + " |")
    return [*lines, "", source(run["source"])]


def render_more(data: dict[str, Any], key: str) -> list[str]:
    """Runs outside the consolidated benchmark: one table per group, each with its own source."""
    del key
    lines: list[str] = []
    for group in data["more"]:
        guide = GUIDE.format(module=group["guide"])
        lines += [
            f"### {group['title']}",
            "",
            f"{group.get('label', data['more_label'])}. {group['note']} Guide: [{group['guide']}]({guide}).",
            "",
            "| " + " | ".join(group["columns"]) + " |",
            "|---|" + "---:|" * (len(group["columns"]) - 1),
        ]
        lines.extend("| " + " | ".join(row) + " |" for row in group["rows"])
        if group.get("footnote"):
            lines += ["", group["footnote"]]
        lines += ["", source(group["source"]), ""]
    return lines[:-1]


def render_table(data: dict[str, Any], key: str) -> list[str]:
    """One hand-entered table (a run with columns of its own), with its caption and source."""
    table = data["tables"][key]
    lines = [
        table["caption"],
        "",
        "| " + " | ".join(table["columns"]) + " |",
        "|---|" + "---:|" * (len(table["columns"]) - 1),
    ]
    lines.extend("| " + " | ".join(row) + " |" for row in table["rows"])
    if table.get("footnote"):
        lines += ["", table["footnote"]]
    return [*lines, "", source(table["source"])]


RENDERERS: dict[str, Callable[[dict[str, Any], str], list[str]]] = {
    "chain": render_chain,
    "stages": render_stages,
    "more": render_more,
    "table": render_table,
}


def render(page: str, data: dict[str, Any]) -> str:
    """The page with every generated block rewritten."""
    pos = 0
    while found := BEGIN.search(page, pos):
        kind, key = found[1], found[2]
        end = f"<!-- bench:{kind}:{key}:end -->"
        stop = page.index(end, found.end()) + len(end)
        lines = [found[0], GENERATED, "", *RENDERERS[kind](data, key), end]
        block = "\n".join(lines)
        page = page[: found.start()] + block + page[stop:]
        pos = found.start() + len(block)
    return page


def main(argv: list[str] | None = None) -> int:
    """Rewrite (or --check) the generated blocks of docs/benchmarks.md."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data", type=Path, default=DATA)
    parser.add_argument("--check", action="store_true", help="fail if the page is out of date")
    args = parser.parse_args(argv)

    data = json.loads(args.data.read_text(encoding="utf-8"))
    page = PAGE.read_text(encoding="utf-8")
    new = render(page, data)
    if args.check:
        if new != page:
            sys.stderr.write(f"{PAGE} is out of date: run python {Path(__file__).as_posix()}\n")
            return 1
        return 0
    PAGE.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
