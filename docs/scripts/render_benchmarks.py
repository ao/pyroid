"""Render the summary table of docs/benchmarks.md from docs/data/benchmarks.json.

The table lives between ``<!-- bench:begin -->`` and ``<!-- bench:end -->``. Each row of the JSON
file has ``module``, ``call``, ``input``, ``incumbent``, ``incumbent_us``, ``pyroid_us``,
``speedup`` and ``check`` (strings, copied as they are: nothing is computed here). To publish the
consolidated harness numbers, replace ``rows``, ``label`` and ``source`` in the JSON file (or pass
another file with ``--data``) and rerun.

Usage (stdlib only, any Python 3.11+, from the repository root):

    python docs/scripts/render_benchmarks.py            # rewrite docs/benchmarks.md
    python docs/scripts/render_benchmarks.py --check    # exit 1 if the page is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

DOCS = Path(__file__).resolve().parent.parent
PAGE = DOCS / "benchmarks.md"
DATA = DOCS / "data" / "benchmarks.json"
BEGIN, END = "<!-- bench:begin -->", "<!-- bench:end -->"
GUIDE = "guides/{module}.md"


def render(data: dict[str, Any]) -> str:
    """The Markdown between the markers."""
    lines = [
        BEGIN,
        "<!-- Generated by docs/scripts/render_benchmarks.py from docs/data/benchmarks.json. -->",
        "",
        f"*{data['label']}.* µs per document, one thread.",
        "",
        "| Module | Call | Input | Incumbent | Incumbent µs/doc | pyroid µs/doc | Speedup "
        "| Output |",
        "|---|---|---|---|---:|---:|---:|---|",
    ]
    for r in data["rows"]:
        module = f"[`pyroid.{r['module']}`]({GUIDE.format(module=r['module'])})"
        lines.append(
            f"| {module} | {r['call']} | {r['input']} | {r['incumbent']} "
            f"| {r['incumbent_us']} | {r['pyroid_us']} | **{r['speedup']}** | {r['check']} |"
        )
    lines += ["", f"<small>Source: {data['source']}.</small>", END]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Rewrite (or --check) the summary block of docs/benchmarks.md."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data", type=Path, default=DATA)
    parser.add_argument("--check", action="store_true", help="fail if the page is out of date")
    args = parser.parse_args(argv)

    data = json.loads(args.data.read_text(encoding="utf-8"))
    page = PAGE.read_text(encoding="utf-8")
    start, end = page.index(BEGIN), page.index(END) + len(END)
    new = page[:start] + render(data) + page[end:]
    if args.check:
        if new != page:
            sys.stderr.write(f"{PAGE} is out of date: run python {Path(__file__).as_posix()}\n")
            return 1
        return 0
    PAGE.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
