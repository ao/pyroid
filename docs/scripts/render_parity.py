"""Render the parity tables of docs/compatibility.md.

The tables live between ``<!-- parity:begin -->`` and ``<!-- parity:end -->``. They are rendered
from one of two sources:

- ``docs/data/parity.json`` (the default): counts entered by hand from the module reports;
- ``--report FILE`` (repeatable): ``parity-report.json`` files written by the parity suites
  (``parity/schema/parity-report.schema.json``, a single run or a ``merge``d one), e.g. the CI
  parity job's artifacts. Suites missing from the reports keep their rows from the seed file.

Usage (stdlib only, any Python 3.11+, from the repository root):

    python docs/scripts/render_parity.py            # rewrite docs/compatibility.md
    python docs/scripts/render_parity.py --check    # exit 1 if the page is out of date
    python docs/scripts/render_parity.py --report parity-ftfy.json --report parity-filters.json
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

DOCS = Path(__file__).resolve().parent.parent
PAGE = DOCS / "compatibility.md"
SEED = DOCS / "data" / "parity.json"
BEGIN, END = "<!-- parity:begin -->", "<!-- parity:end -->"
ORDER = [
    "ftfy",
    "fasttext",
    "filters",
    "dedup",
    "translit",
    "metrics",
    "json_repair",
    "datasketch",
    "jieba",
    "nltk",
    "integrations",
]
TITLES = {
    "ftfy": "pyroid.ftfy",
    "fasttext": "pyroid.fasttext",
    "filters": "pyroid.filters",
    "dedup": "pyroid.dedup",
    "translit": "pyroid.translit",
    "metrics": "pyroid.metrics",
    "json_repair": "pyroid.json_repair",
    "datasketch": "pyroid.datasketch",
    "jieba": "pyroid.jieba",
    "nltk": "pyroid.nltk",
    "integrations": "Integrations: datatrove steps, pyroid clean, pyroid.patch()",
}


def _n(x: int) -> str:
    return f"{x:,}"


def _from_reports(paths: list[Path]) -> dict[str, dict[str, Any]]:
    """Suites from parity-report.json files, one row per (check, interpreter)."""
    suites: dict[str, dict[str, Any]] = {}
    for path in paths:
        data = json.loads(path.read_text(encoding="utf-8"))
        runs = data.get("runs", [data])
        for run in runs:
            env = run["environment"]
            py = env["python"] + ("t" if env.get("free_threaded") else "")
            where = f"CPython {py}, {env['machine']}"
            for name, suite in run["suites"].items():
                if suite["candidate"].get("is_reference"):
                    continue  # a harness self-check, not pyroid
                ref = suite["reference"]
                tol = ref.get("tolerance")
                out = suites.setdefault(
                    name,
                    {
                        "reference": " ".join(
                            str(v) for v in (ref["name"], ref.get("version")) if v
                        ),
                        "rule": f"tolerance {tol}" if tol else "identical",
                        "checks": [],
                        "source": f"parity-report.json ({run['generated_at']})",
                    },
                )
                for check, c in suite["checks"].items():
                    row = {"name": f"{check} ({where})", "same": c["same"], "diff": c["diff"]}
                    if c["status"] == "skip":
                        row["skip"] = c.get("skip_reason", "skipped")
                    out["checks"].append(row)
    return suites


def render(suites: dict[str, dict[str, Any]]) -> str:
    """The Markdown between the markers."""
    lines = [
        BEGIN,
        "<!-- Generated by docs/scripts/render_parity.py from docs/data/parity.json. -->",
    ]
    for name in ORDER:
        s = suites.get(name)
        if s is None:
            continue
        total_same = sum(c["same"] for c in s["checks"])
        total_diff = sum(c["diff"] for c in s["checks"])
        lines += [
            "",
            f"### {TITLES[name]} {{#{name}}}",
            "",
            f"Reference: {s['reference']}. Rule: {s['rule']}.",
            "",
            "| Check | Compared | Identical | Different |",
            "|---|---:|---:|---:|",
        ]
        for c in s["checks"]:
            if "skip" in c:
                lines.append(f"| {c['name']} | skipped: {c['skip']} | | |")
            else:
                total = _n(c["same"] + c["diff"])
                lines.append(f"| {c['name']} | {total} | {_n(c['same'])} | {_n(c['diff'])} |")
        lines += [
            f"| **Total** | **{_n(total_same + total_diff)}** | **{_n(total_same)}** "
            f"| **{_n(total_diff)}** |",
            "",
        ]
        if s.get("notes"):
            lines += [f"- {note}" for note in s["notes"]] + [""]
        lines.append(f"<small>Source: {s['source']}.</small>")
    lines.append(END)
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Rewrite (or --check) the parity block of docs/compatibility.md."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--report", type=Path, action="append", default=[])
    parser.add_argument("--check", action="store_true", help="fail if the page is out of date")
    args = parser.parse_args(argv)

    suites = json.loads(SEED.read_text(encoding="utf-8"))["suites"]
    suites.update(_from_reports(args.report))
    page = PAGE.read_text(encoding="utf-8")
    start, end = page.index(BEGIN), page.index(END) + len(END)
    new = page[:start] + render(suites) + page[end:]
    if args.check:
        if new != page:
            sys.stderr.write(f"{PAGE} is out of date: run python {Path(__file__).as_posix()}\n")
            return 1
        return 0
    PAGE.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
